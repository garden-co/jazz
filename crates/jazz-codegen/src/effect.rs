//! The Effect Schemas companion: `jazz.effect.generated.ts`, beside a TS
//! app's `jazz.generated.ts`.
//!
//! One Effect v4 `Schema.Struct` per table for its row (columns and computed
//! fields) and one for its insert, plus the named field types (enums, typed
//! JSON), under the names `jazz.generated.ts` gives their TS types. Each
//! Schema's `Type` is exactly that TS type, so Effect code (Effect UI's
//! Messages) can carry rows as Schemas. The module imports `Schema` from
//! `effect` and nothing else, so a TS app that doesn't use Effect never
//! needs it: the file is opt-in (`jazz-tools generate --effect-schema`), and
//! once it's there `generate` keeps it current and `--check` checks it.
//!
//! Values are in-memory rows, not their wire form: a timestamp is a `Date`
//! (`Schema.Date`) and bytes a `Uint8Array` (`Schema.Uint8Array`), whose
//! default JSON codecs (`Schema.toCodecJson`) encode them as an ISO string
//! and base64.

use std::fmt::Write as _;

use jazz::tools::public_schema::ColumnType;

use crate::bindings::Staleness;
use crate::model::App;
use crate::ts::{self, ModuleNames, prop, quote};
use crate::{CodegenError, EDIT_NOTE};

/// Where the module goes, beside `jazz.generated.ts`.
pub const FILE: &str = "jazz.effect.generated.ts";

/// The first line, which marks a file as this generator's.
pub const HEADER: &str =
    "// jazz.effect.generated.ts: generated by `jazz-tools generate`. Do not edit.";

/// The version of the module's shape, on its second line. A generator
/// that writes another shape bumps it, so `generate --check` catches
/// Schemas an older Jazz wrote.
pub const FORMAT: u32 = 1;

/// How the second line starts.
const FORMAT_LINE: &str = "// Effect Schemas format ";

const SOURCE: &str = "Source ";
const OUTPUT: &str = "Output ";

/// The digest stands in for this while it's computed.
const OUTPUT_PLACEHOLDER: &str = "................";

/// The one name the module imports, which no table, enum or JSON type may
/// take.
const IMPORTED: &str = "Schema";

/// The second line: the format, the `source` hash of the `jazz.app.json`
/// the Schemas were generated from (as `jazz.generated.ts` records it), and
/// a digest of what this generator wrote, as the TS bindings' format line
/// has. Formatters keep comments, so plain `generate` tells a reformatted
/// module (same digest: kept) from one an older generator wrote (rewritten).
fn format_line(source: &str, output: &str) -> String {
    format!(
        "{FORMAT_LINE}{FORMAT}. {SOURCE}{source}. {OUTPUT}{output}. {EDIT_NOTE} Formatters may reformat this file."
    )
}

/// `jazz.effect.generated.ts` for `app`.
pub fn generate(app: &App) -> Result<String, CodegenError> {
    let ModuleNames { tables, named } = ts::module_names(app)?;
    let taken = tables
        .iter()
        .flat_map(|(table, n)| {
            [
                (n.row.as_str(), format!("table `{table}`")),
                (n.insert.as_str(), format!("table `{table}`'s insert type")),
            ]
        })
        .chain(
            named
                .iter()
                .map(|(name, _, origin)| (name.as_str(), origin.clone())),
        );
    for (name, origin) in taken {
        if name == IMPORTED {
            return Err(CodegenError::new(format!(
                "{origin} would be the Effect Schema `{IMPORTED}`, which {FILE} imports from \
                 effect; rename it in jazz.app.json"
            )));
        }
    }

    let mut out = String::new();
    let _ = writeln!(out, "{HEADER}");
    let _ = writeln!(out, "{}", format_line(&app.source, OUTPUT_PLACEHOLDER));
    let _ = writeln!(out, "import {{ {IMPORTED} }} from \"effect\";");
    out.push('\n');

    for (name, ty, origin) in &named {
        let _ = writeln!(out, "export const {name} = {};", schema(ty, origin)?);
    }
    if !named.is_empty() {
        out.push('\n');
    }

    for table in &app.tables {
        let n = &tables[&table.name];
        let field = |name: &str, ty: &ColumnType, nullable: bool| -> Result<String, CodegenError> {
            let base = match n.fields.get(name) {
                Some(named) => named.clone(),
                None => schema(ty, &format!("`{}.{name}`", table.name))?,
            };
            Ok(null_or(base, nullable))
        };
        let mut row = vec![format!("id: {IMPORTED}.String")];
        let mut insert = Vec::new();
        for column in &table.columns {
            let value = field(
                &column.name,
                &ts::view_type(app, column),
                column.ty.nullable,
            )?;
            row.push(format!("{}: {value}", prop(&column.name)));
            insert.push(format!(
                "{}: {}",
                prop(&column.name),
                if column.optional_on_insert() {
                    format!("{IMPORTED}.optionalKey({value})")
                } else {
                    value
                }
            ));
        }
        for computed in &table.computed {
            let value = field(&computed.name, &computed.ty.ty, computed.ty.nullable)?;
            row.push(format!("{}: {value}", prop(&computed.name)));
        }
        write_struct(&mut out, &n.row, &row);
        out.push('\n');
        write_struct(&mut out, &n.insert, &insert);
        out.push('\n');
    }
    // No trailing blank line.
    out.pop();

    let digest = jazz::tools::deployment::artifact::sha256_hex(out.as_bytes());
    Ok(out.replacen(
        &format!("{OUTPUT}{OUTPUT_PLACEHOLDER}."),
        &format!("{OUTPUT}{}.", &digest[..16]),
        1,
    ))
}

fn write_struct(out: &mut String, name: &str, fields: &[String]) {
    if fields.is_empty() {
        let _ = writeln!(out, "export const {name} = {IMPORTED}.Struct({{}});");
        return;
    }
    let _ = writeln!(out, "export const {name} = {IMPORTED}.Struct({{");
    for field in fields {
        let _ = writeln!(out, "  {field},");
    }
    out.push_str("});\n");
}

fn null_or(schema: String, nullable: bool) -> String {
    if nullable {
        format!("{IMPORTED}.NullOr({schema})")
    } else {
        schema
    }
}

/// The Schema of a value of `ty`, whose `Type` is [`ts::ts_type`]'s.
/// `origin` names the field for a refusal.
pub(crate) fn schema(ty: &ColumnType, origin: &str) -> Result<String, CodegenError> {
    Ok(match ty {
        ColumnType::Text | ColumnType::Uuid => format!("{IMPORTED}.String"),
        ColumnType::Boolean => format!("{IMPORTED}.Boolean"),
        ColumnType::Integer | ColumnType::Double => format!("{IMPORTED}.Number"),
        ColumnType::BigInt => format!("{IMPORTED}.BigInt"),
        ColumnType::Timestamp => format!("{IMPORTED}.Date"),
        ColumnType::Bytea => format!("{IMPORTED}.Uint8Array"),
        // `JsonValue`'s arrays and objects are mutable.
        ColumnType::Json { schema: None } => format!("{IMPORTED}.MutableJson"),
        ColumnType::Json {
            schema: Some(json_schema),
        } => crate::json_schema::to_effect(json_schema).map_err(|what| {
            CodegenError::unsupported(format!(
                "{origin}: {what} in a JSON Schema is not supported in Effect Schemas yet"
            ))
        })?,
        ColumnType::Enum { variants } | ColumnType::ScalarEnum { variants, .. } => {
            if variants.is_empty() {
                format!("{IMPORTED}.Never")
            } else {
                literals(variants.iter().map(|v| quote(v)).collect())
            }
        }
        ColumnType::Array { element } => mutable_array(schema(element, origin)?),
        ColumnType::TransactionId
        | ColumnType::Row { .. }
        | ColumnType::LegacyEnumPayload { .. } => format!("{IMPORTED}.Unknown"),
    })
}

/// `Schema.Literals([…])` of JS literals.
pub(crate) fn literals(items: Vec<String>) -> String {
    format!("{IMPORTED}.Literals([{}])", items.join(", "))
}

/// An array whose `Type` is `T[]`, as the TS bindings' arrays are (a plain
/// `Schema.Array`'s is `ReadonlyArray<T>`).
pub(crate) fn mutable_array(element: String) -> String {
    format!("{IMPORTED}.mutable({IMPORTED}.Array({element}))")
}

/// What a committed module records.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Recorded {
    pub format: u32,
    /// `sha256:…` of the `jazz.app.json` it was generated from.
    pub source: String,
    /// The digest of what the generator wrote.
    pub output: String,
}

/// Read what a module this generator wrote records on its format line.
pub fn read(text: &str) -> Result<Recorded, CodegenError> {
    let refuse = |what: &str| {
        CodegenError::new(format!(
            "{FILE}: {what}; regenerate it with `npx jazz-tools generate`"
        ))
    };
    let text = text.strip_prefix('\u{feff}').unwrap_or(text);
    if !text.trim_start().starts_with(HEADER) {
        return Err(refuse(
            "not a module jazz-tools generated (its first line differs)",
        ));
    }
    let line = text
        .lines()
        .find_map(|line| line.trim().strip_prefix(FORMAT_LINE))
        .ok_or_else(|| refuse(&format!("no `{FORMAT_LINE}<n>.` line")))?;
    let format = line
        .split('.')
        .next()
        .and_then(|n| n.parse::<u32>().ok())
        .ok_or_else(|| refuse("its format line has no format"))?;
    let after = |marker: &str| -> Option<String> {
        let at = line.find(marker)? + marker.len();
        line[at..].split('.').next().map(str::to_string)
    };
    let source = after(SOURCE)
        .filter(|s| s.starts_with("sha256:"))
        .ok_or_else(|| refuse("its format line has no source"))?;
    let output = after(OUTPUT)
        .filter(|d| d.len() == 16 && d.chars().all(|c| c.is_ascii_hexdigit()))
        .ok_or_else(|| refuse("its format line has no output digest"))?;
    Ok(Recorded {
        format,
        source,
        output,
    })
}

/// Whether `committed` (the file, if there is one) fits `app`: by its
/// source and format, as for the TS bindings. A schema change without a
/// migration is the TS bindings' to catch; these Schemas hold no version.
pub fn staleness(app: &App, committed: Option<&str>) -> Option<Staleness> {
    let Some(committed) = committed else {
        return Some(Staleness::Missing);
    };
    match read(committed) {
        Err(error) => Some(Staleness::Unreadable(error.message().to_string())),
        Ok(recorded) if recorded.source != app.source || recorded.format != FORMAT => {
            Some(Staleness::OutOfDate)
        }
        Ok(_) => None,
    }
}

/// Whether `committed` is other than what the generator writes now
/// (`generated`), formatting aside: what plain `generate` rewrites.
pub fn output_changed(committed: &str, generated: &str) -> bool {
    let digest = |text: &str| read(text).ok().map(|r| r.output);
    digest(committed) != digest(generated)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn app(json: &str) -> App {
        App::load(json.as_bytes()).unwrap()
    }

    const TODOS: &str = r#"{ "format": 1, "tables": { "todos": { "columns": {
        "title": "string",
        "done": { "type": "boolean", "default": false },
        "note": "string?",
        "status": { "enum": ["todo", "done"] },
        "tags": { "array": "string" },
        "at": "timestamp",
        "blob": "bytes?",
        "big": "bigint",
        "data": { "json": true },
        "point": { "json": { "type": "object", "properties": { "x": { "type": "number" }, "y": { "type": "number" } }, "required": ["x"], "additionalProperties": false } }
    }, "computed": { "label": { "type": "string?", "from": ["title"] } } } } }"#;

    #[test]
    fn each_table_gets_a_row_and_an_insert_schema() {
        let generated = generate(&app(TODOS)).unwrap();
        let body = generated.split_once("\n\n").unwrap().1;
        assert_eq!(
            body,
            r#"export const TodoStatus = Schema.Literals(["todo", "done"]);
export const TodoPoint = Schema.Struct({ x: Schema.Number, y: Schema.optionalKey(Schema.Number) });

export const Todo = Schema.Struct({
  id: Schema.String,
  title: Schema.String,
  done: Schema.Boolean,
  note: Schema.NullOr(Schema.String),
  status: TodoStatus,
  tags: Schema.mutable(Schema.Array(Schema.String)),
  at: Schema.Date,
  blob: Schema.NullOr(Schema.Uint8Array),
  big: Schema.BigInt,
  data: Schema.MutableJson,
  point: TodoPoint,
  label: Schema.NullOr(Schema.String),
});

export const TodoInsert = Schema.Struct({
  title: Schema.String,
  done: Schema.optionalKey(Schema.Boolean),
  note: Schema.optionalKey(Schema.NullOr(Schema.String)),
  status: TodoStatus,
  tags: Schema.mutable(Schema.Array(Schema.String)),
  at: Schema.Date,
  blob: Schema.optionalKey(Schema.NullOr(Schema.Uint8Array)),
  big: Schema.BigInt,
  data: Schema.MutableJson,
  point: TodoPoint,
});
"#
        );
        let mut lines = generated.lines();
        assert_eq!(lines.next(), Some(HEADER));
        assert!(lines.next().unwrap().contains(&app(TODOS).source));
        assert_eq!(lines.next(), Some("import { Schema } from \"effect\";"));
    }

    #[test]
    fn the_names_are_the_typescript_bindings_names() {
        let app = app(TODOS);
        let ts = ts::generate(&app).unwrap();
        let effect = generate(&app).unwrap();
        for name in ["TodoStatus", "TodoPoint", "Todo", "TodoInsert"] {
            assert!(ts.contains(&format!("export type {name} = ")), "{name}");
            assert!(
                effect.contains(&format!("export const {name} = ")),
                "{name}"
            );
        }
    }

    #[test]
    fn a_table_named_like_the_import_is_refused() {
        let error = generate(&app(
            r#"{ "format": 1, "tables": { "schemas": { "columns": { "name": "string" } } } }"#,
        ))
        .unwrap_err();
        assert!(
            error
                .message()
                .contains("table `schemas` would be the Effect Schema `Schema`"),
            "{error}"
        );
    }

    #[test]
    fn json_schema_it_cant_express_is_refused_as_unsupported() {
        let error = generate(&app(
            r#"{ "format": 1, "tables": { "todos": { "columns": { "meta": { "json": { "allOf": [{ "type": "object" }, { "type": "object" }] } } } } } }"#,
        ))
        .unwrap_err();
        assert!(error.is_unsupported());
        assert_eq!(
            error.message(),
            "`todos.meta`: `allOf` in a JSON Schema is not supported in Effect Schemas yet"
        );
    }

    #[test]
    fn a_module_records_its_source_format_and_output() {
        let app = app(TODOS);
        let generated = generate(&app).unwrap();
        let recorded = read(&generated).unwrap();
        assert_eq!(recorded.source, app.source);
        assert_eq!(recorded.format, FORMAT);
        // The digest is of the module with the digest left out.
        let without = generated.replacen(&recorded.output, OUTPUT_PLACEHOLDER, 1);
        assert_eq!(
            &jazz::tools::deployment::artifact::sha256_hex(without.as_bytes())[..16],
            recorded.output
        );
        assert_eq!(staleness(&app, Some(&generated)), None);
        assert_eq!(staleness(&app, None), Some(Staleness::Missing));
        // Reformatted: current, and not rewritten.
        let reformatted = generated.replace("\n\n", "\n\n\n");
        assert_eq!(staleness(&app, Some(&reformatted)), None);
        assert!(!output_changed(&reformatted, &generated));
        // From another app file, or another format: out of date.
        let other = generated.replace(&app.source, &format!("sha256:{}", "0".repeat(64)));
        assert_eq!(staleness(&app, Some(&other)), Some(Staleness::OutOfDate));
        let older = generated.replacen(
            &format!("{FORMAT_LINE}{FORMAT}."),
            &format!("{FORMAT_LINE}0."),
            1,
        );
        assert_eq!(staleness(&app, Some(&older)), Some(Staleness::OutOfDate));
        // Another generator's output: rewritten.
        assert!(output_changed(
            &generated.replacen(&recorded.output, "0123456789abcdef", 1),
            &generated
        ));
        // Not this generator's.
        assert!(matches!(
            staleness(&app, Some("export const x = 1;\n")),
            Some(Staleness::Unreadable(why)) if why.contains("its first line differs")
        ));
    }
}
