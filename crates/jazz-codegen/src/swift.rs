//! The Swift back end: `JazzApp.swift`, typed bindings over the `Jazz`
//! Swift package (`packages/jazz-swift`, which wraps `crates/jazz-ffi`).
//!
//! Per table: a `Codable` row struct (`Todo`), an insert struct (`NewTodo`)
//! and a patch struct (`TodoPatch`), with lowerCamelCase properties mapped
//! to the authored names by `CodingKeys`, and a namespace (`todos`) with the
//! table's query and typed columns, which build the query JSON jazz-ffi
//! reads. Everything sits inside `public enum JazzApp`, which also embeds
//! `jazz.app.json` and opens it: `JazzApp.Todo`, `JazzApp.todos.query()`.
//!
//! Computed fields and transforms are declared in `JazzApp.Computed`,
//! which the app implements. Each relation is a row property, filled when a query includes it
//! (`JazzApp.tasks.query().include(JazzApp.tasks.assignee)`).

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

use jazz::tools::public_schema::ColumnType;

use crate::CodegenError;
use crate::model::{App, Column, FieldType, RelationKind, Table};
use crate::names::{pascal, singular};

/// Where the bindings go, relative to `jazz.app.json`.
pub const FILE: &str = "JazzApp.swift";

/// The version of the bindings' shape this generator writes: the second
/// line records it.
pub const FORMAT: u32 = 1;

/// The first line, which marks a file as this generator's.
pub const HEADER: &str = "// JazzApp.swift: generated by `jazz-tools generate`. Do not edit.";

/// The first line before alpha.66, which the reader still accepts: bindings
/// it heads are current while their source and format are, and the next
/// `generate` rewrites them with [`HEADER`].
pub(crate) const LEGACY_HEADER: &str =
    "// JazzApp.swift: generated from jazz.app.json by `jazz-tools generate`. Do not edit.";

const FORMAT_PREFIX: &str = "// Bindings format ";

/// How the embedded `jazz.app.json` starts: a raw multi-line string follows.
const APP_PREFIX: &str = "    public static let app = ";

/// The enum that holds the recorded source and the embedded app.
const JAZZ_APP_OPEN: &str = "\npublic enum JazzApp {\n";

/// How the recorded source starts.
const SOURCE_PREFIX: &str = "    public static let source = ";

/// The runtime module.
const RT: &str = "Jazz";

/// What `JazzApp` declares itself, besides the generated types.
const MEMBERS: &[&str] = &["source", "app", "open", "computed"];

/// Type names the bindings or their imports declare.
const RESERVED: &[&str] = &[
    "Computed",
    "Jazz",
    "JazzApp",
    "Swift",
    "Foundation",
    "Self",
    "Type",
    "Protocol",
];

pub fn generate(app: &App) -> Result<String, CodegenError> {
    Writer::new(app)?.write()
}

/// Whether `manifest` (a `Package.swift`) is a package that uses the Jazz
/// Swift runtime: a target depends on its product, `.product(name: "Jazz",
/// …)` (the Jazz repository's root package, by URL or path), or it names
/// the `jazz-swift` package, as a quoted name or the last part of a quoted
/// path or URL, not merely mentions it.
pub fn is_app_manifest(manifest: &str) -> bool {
    let uses_product = manifest.match_indices(".product(").any(|(at, word)| {
        let args = &manifest[at + word.len()..];
        let args: String = args[..args.find(')').unwrap_or(args.len())]
            .chars()
            .filter(|c| !c.is_whitespace())
            .collect();
        args.starts_with("name:\"Jazz\"")
    });
    uses_product
        || manifest.match_indices("jazz-swift").any(|(at, word)| {
            let before = manifest[..at].chars().next_back();
            let after = &manifest[at + word.len()..];
            matches!(before, Some('"' | '/'))
                && (after.starts_with('"') || after.starts_with(".git\""))
        })
}

struct TableNames {
    row: String,
    new: String,
    patch: String,
    namespace: String,
}

struct Writer<'a> {
    app: &'a App,
    tables: BTreeMap<&'a str, TableNames>,
    /// Generated enums by Swift name: cases (Swift name, stored name), and
    /// what declared them.
    enums: BTreeMap<String, (Vec<(String, String)>, String)>,
    /// Every type name taken, with what took it.
    types: BTreeMap<String, String>,
    /// Whether the app declares computed fields or transforms: then
    /// `JazzApp.Computed` declares them and `open` takes an implementation.
    has_computed: bool,
}

impl<'a> Writer<'a> {
    fn new(app: &'a App) -> Result<Self, CodegenError> {
        let mut writer = Self {
            app,
            tables: BTreeMap::new(),
            enums: BTreeMap::new(),
            has_computed: !app.transforms.is_empty()
                || app.tables.iter().any(|table| !table.computed.is_empty()),
            types: RESERVED
                .iter()
                .map(|name| (name.to_string(), "a name the bindings use".to_string()))
                .collect(),
        };
        let mut namespaces = BTreeMap::new();
        for table in &app.tables {
            let row = type_ident(&pascal(&singular(&table.name)), &table.name)?;
            // The table's namespace is its lowerCamelCase name, like a Rust
            // module: `JazzApp.tasks.query()`, `JazzApp.tasks.rank`.
            let namespace = value_ident(&table.name)?;
            let bare = namespace.trim_matches('`').to_owned();
            if MEMBERS.contains(&bare.as_str()) {
                return Err(CodegenError::unsupported(format!(
                    "table `{}` is the Swift name `JazzApp.{bare}`, which the bindings use themselves",
                    table.name
                )));
            }
            if let Some(other) = namespaces.insert(bare.clone(), table.name.clone()) {
                return Err(CodegenError::unsupported(format!(
                    "tables `{other}` and `{}` are both the Swift name `JazzApp.{bare}`",
                    table.name
                )));
            }
            let what = format!("table `{}`", table.name);
            for name in [row.clone(), format!("New{row}"), format!("{row}Patch")] {
                writer.take_type(&name, &what)?;
            }
            writer.tables.insert(
                &table.name,
                TableNames {
                    new: format!("New{row}"),
                    patch: format!("{row}Patch"),
                    row,
                    namespace,
                },
            );
        }
        Ok(writer)
    }

    fn take_type(&mut self, name: &str, what: &str) -> Result<(), CodegenError> {
        match self.types.insert(name.to_owned(), what.to_owned()) {
            Some(other) => Err(CodegenError::unsupported(format!(
                "{what} and {other} are both the Swift type `{name}`"
            ))),
            None => Ok(()),
        }
    }

    fn write(mut self) -> Result<String, CodegenError> {
        let mut items = String::new();
        for table in &self.app.tables {
            items.push_str(&self.table(table)?);
        }
        items.push_str(&self.computed_protocol()?);

        let mut out = String::new();
        let _ = writeln!(out, "{HEADER}");
        let _ = writeln!(out, "{FORMAT_PREFIX}{FORMAT}. {}", crate::EDIT_NOTE);
        out.push_str("// swift-format-ignore-file\n\n");
        out.push_str("import Foundation\nimport Jazz\n\n");
        out.push_str(
            "/// The app: its `jazz.app.json`, opening it, and a type per table and enum,\n\
             /// all inside this namespace so table names never hide Swift's own types\n\
             /// (`JazzApp.Task`, not `Task`).\n",
        );
        out.push_str(&JAZZ_APP_OPEN[1..]);
        out.push_str(&self.open());
        let mut nested = String::new();
        for (name, (cases, what)) in &self.enums {
            let _ = writeln!(nested, "/// The values of {what}.");
            let _ = writeln!(
                nested,
                "public enum {name}: Swift.String, Swift.Codable, Swift.Sendable, Swift.Hashable, Swift.CaseIterable {{"
            );
            for (case, stored) in cases {
                let _ = writeln!(nested, "    case {case} = {}", swift_string(stored));
            }
            nested.push_str("}\n\n");
        }
        nested.push_str(&items);
        for line in nested.trim_end().lines() {
            if !line.is_empty() {
                out.push_str("    ");
            }
            out.push_str(line);
            out.push('\n');
        }
        out.push_str("}\n");
        Ok(out)
    }

    /// The Swift type of a value of `ty`; `name` and `what` name a
    /// generated enum.
    fn swift_type(
        &mut self,
        ty: &ColumnType,
        name: &str,
        what: &str,
    ) -> Result<String, CodegenError> {
        Ok(match ty {
            ColumnType::Integer => "Swift.Int".into(),
            ColumnType::BigInt => format!("{RT}.BigInt"),
            ColumnType::Boolean => "Swift.Bool".into(),
            ColumnType::Text => "Swift.String".into(),
            ColumnType::Double => "Swift.Double".into(),
            ColumnType::Timestamp => "Foundation.Date".into(),
            ColumnType::Uuid => format!("{RT}.ID"),
            ColumnType::Bytea => "Foundation.Data".into(),
            ColumnType::Json { .. } => format!("{RT}.JSONValue"),
            ColumnType::Array { element } => {
                format!("[{}]", self.swift_type(element, name, what)?)
            }
            ColumnType::Enum { variants } => {
                let mut cases = Vec::new();
                let mut seen = BTreeMap::new();
                for variant in variants {
                    let ident = value_ident(variant)?;
                    if let Some(other) = seen.insert(ident.clone(), variant.clone()) {
                        return Err(CodegenError::unsupported(format!(
                            "{what}: values `{other}` and `{variant}` are both the Swift case `{ident}`"
                        )));
                    }
                    cases.push((ident, variant.clone()));
                }
                match self.enums.get(name) {
                    Some((existing, _)) if *existing == cases => {}
                    _ => {
                        self.take_type(name, what)?;
                        self.enums.insert(name.to_owned(), (cases, what.to_owned()));
                    }
                }
                name.to_owned()
            }
            _ => {
                return Err(CodegenError::unsupported(format!(
                    "{what}: values of this type in Swift bindings are not supported yet"
                )));
            }
        })
    }

    fn field_type(
        &mut self,
        ty: &FieldType,
        name: &str,
        what: &str,
    ) -> Result<String, CodegenError> {
        let inner = self.swift_type(&ty.ty, name, what)?;
        Ok(if ty.nullable {
            format!("{inner}?")
        } else {
            inner
        })
    }

    /// A column as the bindings type it: through its transform, if any.
    fn field<'c>(
        &mut self,
        row: &str,
        column: &'c Column,
        ident: String,
        what: &str,
    ) -> Result<Field<'c>, CodegenError> {
        let wrap = |ty: String| {
            if column.ty.nullable {
                format!("{ty}?")
            } else {
                ty
            }
        };
        let (ty, stored, transform) = match &column.transform {
            Some(name) => {
                let (stored, view) = self.transform_types(name)?;
                (
                    wrap(view),
                    wrap(stored),
                    Some(value_ident(name)?.trim_matches('`').to_owned()),
                )
            }
            None => {
                let ty =
                    self.field_type(&column.ty, &format!("{row}{}", pascal(&column.name)), what)?;
                (ty.clone(), ty, None)
            }
        };
        Ok(Field {
            column,
            ident,
            ty,
            stored,
            transform,
        })
    }

    /// The stored and view types of transform `name`.
    fn transform_types(&mut self, name: &str) -> Result<(String, String), CodegenError> {
        let transform = self
            .app
            .transform(name)
            .ok_or_else(|| CodegenError::new(format!("transform `{name}` is not declared")))?;
        let what = format!("transform `{name}`");
        let base = type_ident(&pascal(&words(name).join("_")), name)?;
        let stored = self.swift_type(&transform.stored, &format!("{base}Stored"), &what)?;
        let view = self.swift_type(&transform.view, &format!("{base}View"), &what)?;
        Ok((stored, view))
    }

    /// `JazzApp.Computed`: each computed field and each transform both ways.
    fn computed_protocol(&mut self) -> Result<String, CodegenError> {
        if !self.has_computed {
            return Ok(String::new());
        }
        let mut out = String::new();
        out.push_str(
            "/// What the app's code computes: each computed field `jazz.app.json`\n\
             /// declares, and each transform both ways. `JazzApp.open(_:computed:)` takes an\n\
             /// implementation; a missing method is a compile error.\n",
        );
        out.push_str("public protocol Computed: Swift.Sendable {\n");
        let mut methods = BTreeSet::new();
        for table in &self.app.tables {
            let row = self.tables[table.name.as_str()].row.clone();
            for c in &table.computed {
                let what = format!("computed field `{}.{}`", table.name, c.name);
                let ret = self.field_type(&c.ty, &format!("{row}{}", pascal(&c.name)), &what)?;
                let mut args = Vec::new();
                for from in &c.from {
                    if from == "id" {
                        args.push(format!("id: {RT}.ID"));
                        continue;
                    }
                    let column = table.column(from).ok_or_else(|| {
                        CodegenError::new(format!(
                            "{what} is computed from `{from}`, which is not a column"
                        ))
                    })?;
                    let ident = value_ident(from)?;
                    let what = format!("column `{}.{}`", table.name, column.name);
                    let field = self.field(&row, column, ident, &what)?;
                    args.push(format!("{}: {}", field.ident.trim_matches('`'), field.ty));
                }
                let method = computed_method(table, c)?;
                if !methods.insert(method.clone()) {
                    return Err(CodegenError::unsupported(format!(
                        "two `JazzApp.Computed` methods are named `{method}`"
                    )));
                }
                let _ = writeln!(
                    out,
                    "    /// `{}.{}`.\n    func {method}({}) -> {ret}\n",
                    table.name,
                    c.name,
                    args.join(", ")
                );
            }
        }
        for transform in &self.app.transforms {
            let (stored, view) = self.transform_types(&transform.name)?;
            let stem = value_ident(&transform.name)?.trim_matches('`').to_owned();
            for method in [format!("{stem}View"), format!("{stem}Stored")] {
                if !methods.insert(method.clone()) {
                    return Err(CodegenError::unsupported(format!(
                        "two `JazzApp.Computed` methods are named `{method}`"
                    )));
                }
            }
            let _ = writeln!(
                out,
                "    /// Transform `{0}`: a stored value, as the app reads it.\n    func {stem}View(_ stored: {stored}) -> {view}\n\n    /// Transform `{0}`: a value the app writes, as stored.\n    func {stem}Stored(_ view: {view}) -> {stored}\n",
                transform.name
            );
        }
        let mut out = out.trim_end().to_owned();
        out.push_str("\n}\n\n");
        Ok(out)
    }

    fn table(&mut self, table: &'a Table) -> Result<String, CodegenError> {
        let names = &self.tables[table.name.as_str()];
        let (row, new, patch, namespace) = (
            names.row.clone(),
            names.new.clone(),
            names.patch.clone(),
            names.namespace.clone(),
        );
        // `self` is no property name even in backticks.
        let mut idents = BTreeSet::from(["id".to_owned(), "query".to_owned(), "self".to_owned()]);
        let mut fields = Vec::new();
        for column in &table.columns {
            let ident = value_ident(&column.name)?;
            if !idents.insert(ident.trim_matches('`').to_owned()) {
                return Err(CodegenError::unsupported(format!(
                    "`{}.{}` is the Swift name `{ident}`, which another column, `id`, `query` or `self` already is",
                    table.name, column.name
                )));
            }
            let what = format!("column `{}.{}`", table.name, column.name);
            fields.push(self.field(&row, column, ident, &what)?);
        }
        let mut computed = Vec::new();
        for c in &table.computed {
            let ident = value_ident(&c.name)?;
            if !idents.insert(ident.trim_matches('`').to_owned()) {
                return Err(CodegenError::unsupported(format!(
                    "computed field `{}.{}` is the Swift name `{ident}`, which a column, `id`, `query` or `self` already is",
                    table.name, c.name
                )));
            }
            let what = format!("computed field `{}.{}`", table.name, c.name);
            let ty = self.field_type(&c.ty, &format!("{row}{}", pascal(&c.name)), &what)?;
            let method = computed_method(table, c)?;
            let mut args = Vec::new();
            for from in &c.from {
                if from == "id" {
                    args.push(("id".to_owned(), format!("{RT}.ID")));
                    continue;
                }
                let field = fields
                    .iter()
                    .find(|f| f.column.name == *from)
                    .ok_or_else(|| {
                        CodegenError::new(format!(
                            "{what} is computed from `{from}`, which is not a column"
                        ))
                    })?;
                args.push((field.ident.clone(), field.ty.clone()));
            }
            computed.push(ComputedField {
                ident,
                ty,
                method,
                args,
            });
        }
        // Relations: filled when a query includes them, `nil` otherwise.
        let mut relations = Vec::new();
        for r in &table.relations {
            let ident = value_ident(&r.name)?;
            let bare = ident.trim_matches('`').to_owned();
            if !idents.insert(bare.clone()) {
                return Err(CodegenError::unsupported(format!(
                    "relation `{}.{}` is the Swift name `{ident}`, which a column, computed field, `id`, `query` or `self` already is",
                    table.name, r.name
                )));
            }
            let target = self
                .tables
                .get(r.target.as_str())
                .ok_or_else(|| {
                    CodegenError::new(format!(
                        "relation `{}.{}` leads to `{}`, which is not a table",
                        table.name, r.name, r.target
                    ))
                })?
                .row
                .clone();
            let to_many = match &r.kind {
                RelationKind::Many { .. } => true,
                RelationKind::One { column, .. } => table
                    .column(column)
                    .is_some_and(|c| matches!(c.ty.ty, ColumnType::Array { .. })),
            };
            relations.push(RelationField {
                name: r.name.clone(),
                ident,
                bare,
                target,
                to_many,
            });
        }
        let custom = !computed.is_empty() || fields.iter().any(|f| f.transform.is_some());
        let table_lit = swift_string(&table.name);

        let mut out = String::new();
        // The row.
        let _ = writeln!(out, "/// A row of `{}`.", table.name);
        let _ = writeln!(out, "public struct {row}: {RT}.Row {{");
        let _ = writeln!(out, "    public static let table = {table_lit}");
        let _ = writeln!(out, "    public let id: {RT}.ID");
        for f in &fields {
            f.doc(&mut out);
            let _ = writeln!(out, "    public var {}: {}", f.ident, f.ty);
        }
        for c in &computed {
            let from = c
                .args
                .iter()
                .map(|(a, _)| format!("`{}`", a.trim_matches('`')))
                .collect::<Vec<_>>()
                .join(", ");
            let _ = writeln!(
                out,
                "    /// Computed from {from} by `JazzApp.Computed.{}`.",
                c.method
            );
            let _ = writeln!(out, "    public internal(set) var {}: {}", c.ident, c.ty);
        }
        for r in &relations {
            if r.to_many {
                let _ = writeln!(
                    out,
                    "    /// Relation `{}`: the `{}` rows, when the query includes them.\n    public var {}: [{}]? = nil",
                    r.name, r.target, r.ident, r.target
                );
            } else {
                // Boxed: tables that point at each other would otherwise
                // make row types of infinite size.
                let _ = writeln!(
                    out,
                    "    /// Relation `{0}`: the `{1}` row, when the query includes it (and it exists).\n    public var {2}: {1}? {{\n        get {{ _{3}?.value }}\n        set {{ _{3} = newValue.map {{ {RT}.Included($0) }} }}\n    }}\n    private var _{3}: {RT}.Included<{1}>? = nil",
                    r.name, r.target, r.ident, r.bare
                );
            }
        }
        out.push('\n');
        let computed_params: String = computed
            .iter()
            .map(|c| format!(", {}: {}", c.ident, c.ty))
            .collect();
        let _ = writeln!(
            out,
            "    public init(id: {RT}.ID{}{computed_params}) {{",
            params(&fields, false)
        );
        out.push_str("        self.id = id\n");
        for f in &fields {
            let _ = writeln!(out, "        self.{0} = {0}", f.ident);
        }
        for c in &computed {
            let _ = writeln!(out, "        self.{0} = {0}", c.ident);
        }
        out.push_str("    }\n\n");
        if !relations.is_empty() {
            // A row is equal to itself whatever a query included with it
            // (`watch` diffing, SwiftUI): relations stay out of `==` and `hash`.
            let mut compared = vec!["id".to_owned()];
            compared.extend(fields.iter().map(|f| f.ident.clone()));
            compared.extend(computed.iter().map(|c| c.ident.clone()));
            let _ = writeln!(
                out,
                "    /// Equal by id, columns and computed fields: included relations don't count.\n    public static func == (a: Self, b: Self) -> Swift.Bool {{\n        {}\n    }}\n",
                compared
                    .iter()
                    .map(|x| format!("a.{x} == b.{x}"))
                    .collect::<Vec<_>>()
                    .join(" && ")
            );
            out.push_str("    public func hash(into hasher: inout Swift.Hasher) {\n");
            for x in &compared {
                let _ = writeln!(out, "        hasher.combine({x})");
            }
            out.push_str("    }\n\n");
        }
        coding_keys(&mut out, &fields, true);
        if !relations.is_empty() {
            // The relations' keys join the row's coding keys.
            let close = out.rfind("    }\n").expect("coding keys were written");
            let mut keys = String::new();
            for r in &relations {
                let key = if r.to_many {
                    r.ident.clone()
                } else {
                    format!("_{}", r.bare)
                };
                let _ = writeln!(keys, "        case {key} = {}", swift_string(&r.name));
            }
            out.insert_str(close, &keys);
        }
        if custom {
            out.push_str("\n    public init(from decoder: any Swift.Decoder) throws {\n");
            out.push_str(
                "        let container = try decoder.container(keyedBy: CodingKeys.self)\n",
            );
            out.push_str("        let computed = try Jazz.implementations(of: (any Computed).self, in: decoder.userInfo)\n");
            out.push_str("        self.id = try container.decode(Jazz.ID.self, forKey: .id)\n");
            for f in &fields {
                let _ = writeln!(out, "        self.{} = {}", f.ident, f.decode());
            }
            for r in &relations {
                let (key, ty) = if r.to_many {
                    (r.ident.clone(), format!("[{}]", r.target))
                } else {
                    (
                        format!("_{}", r.bare),
                        format!("{RT}.Included<{}>", r.target),
                    )
                };
                let _ = writeln!(
                    out,
                    "        self.{key} = try container.decodeIfPresent({ty}.self, forKey: .{key})"
                );
            }
            for c in &computed {
                let args = c
                    .args
                    .iter()
                    .map(|(a, _)| {
                        let bare = a.trim_matches('`');
                        format!("{bare}: self.{a}")
                    })
                    .collect::<Vec<_>>()
                    .join(", ");
                let _ = writeln!(
                    out,
                    "        self.{} = computed.{}({args})",
                    c.ident, c.method
                );
            }
            out.push_str("    }\n\n");
            out.push_str("    public func encode(to encoder: any Swift.Encoder) throws {\n");
            out.push_str("        var container = encoder.container(keyedBy: CodingKeys.self)\n");
            // Only a transform needs the implementations to encode a row.
            let transforms = fields.iter().any(|f| f.transform.is_some());
            if transforms {
                out.push_str("        let computed = try Jazz.implementations(of: (any Computed).self, in: encoder.userInfo)\n");
            }
            out.push_str("        try container.encode(self.id, forKey: .id)\n");
            for f in &fields {
                let _ = writeln!(out, "        {}", f.encode(false));
            }
            for r in &relations {
                let key = if r.to_many {
                    r.ident.clone()
                } else {
                    format!("_{}", r.bare)
                };
                let _ = writeln!(
                    out,
                    "        try container.encodeIfPresent(self.{key}, forKey: .{key})"
                );
            }
            if transforms {
                out.push_str("        _ = computed\n");
            }
            out.push_str("    }\n");
        }
        out.push_str("}\n\n");

        // New rows.
        let _ = writeln!(
            out,
            "/// A new row of `{}`: `nil` leaves a column out, which stores its default (or `null`).",
            table.name
        );
        let _ = writeln!(out, "public struct {new}: {RT}.Insert {{");
        let _ = writeln!(out, "    public typealias Row = {row}");
        for f in &fields {
            f.doc(&mut out);
            let _ = writeln!(out, "    public var {}: {}", f.ident, f.insert_type());
        }
        out.push('\n');
        let p = params(&fields, true);
        let _ = writeln!(out, "    public init({}) {{", p.trim_start_matches(", "));
        for f in &fields {
            let _ = writeln!(out, "        self.{0} = {0}", f.ident);
        }
        out.push_str("    }\n\n");
        coding_keys(&mut out, &fields, false);
        if fields.iter().any(|f| f.transform.is_some()) {
            out.push_str("\n    public func encode(to encoder: any Swift.Encoder) throws {\n");
            out.push_str("        var container = encoder.container(keyedBy: CodingKeys.self)\n");
            out.push_str("        let computed = try Jazz.implementations(of: (any Computed).self, in: encoder.userInfo)\n");
            for f in &fields {
                let _ = writeln!(out, "        {}", f.encode(true));
            }
            out.push_str("        _ = computed\n");
            out.push_str("    }\n");
        }
        out.push_str("}\n\n");

        // Patches.
        let _ = writeln!(
            out,
            "/// A change to a row of `{}`: only the columns set to `.set(…)` change; `.set(nil)` stores `null`.",
            table.name
        );
        let _ = writeln!(out, "public struct {patch}: {RT}.Patch {{");
        let _ = writeln!(out, "    public typealias Row = {row}");
        for f in &fields {
            f.doc(&mut out);
            let _ = writeln!(out, "    public var {}: {RT}.Change<{}>", f.ident, f.ty);
        }
        out.push('\n');
        let p = fields
            .iter()
            .map(|f| format!("{}: {RT}.Change<{}> = .unchanged", f.ident, f.ty))
            .collect::<Vec<_>>()
            .join(", ");
        let _ = writeln!(out, "    public init({p}) {{");
        for f in &fields {
            let _ = writeln!(out, "        self.{0} = {0}", f.ident);
        }
        out.push_str("    }\n\n");
        coding_keys(&mut out, &fields, false);
        out.push('\n');
        out.push_str("    public func encode(to encoder: any Swift.Encoder) throws {\n");
        out.push_str("        var container = encoder.container(keyedBy: CodingKeys.self)\n");
        if fields.iter().any(|f| f.transform.is_some()) {
            out.push_str("        let computed = try Jazz.implementations(of: (any Computed).self, in: encoder.userInfo)\n");
        }
        for f in &fields {
            let value = match &f.transform {
                None => format!("self.{}", f.ident),
                Some(t) if f.column.ty.nullable => format!(
                    "self.{}.map {{ $0.map {{ computed.{t}Stored($0) }} }}",
                    f.ident
                ),
                Some(t) => format!("self.{}.map {{ computed.{t}Stored($0) }}", f.ident),
            };
            let _ = writeln!(
                out,
                "        try container.encodeChange({value}, forKey: .{})",
                f.ident
            );
        }
        out.push_str("    }\n}\n\n");

        // Queries and columns.
        let _ = writeln!(out, "/// Queries of `{}` and its columns.", table.name);
        let _ = writeln!(out, "public enum {namespace} {{");
        let _ = writeln!(
            out,
            "    /// Every row of `{}`; narrow it with `where`, `orderBy`, `limit` and `offset`.",
            table.name
        );
        let _ = writeln!(
            out,
            "    public static func query() -> {RT}.Query<{row}> {{ {RT}.Query() }}"
        );
        out.push('\n');
        out.push_str("    /// The row's id.\n");
        let _ = writeln!(
            out,
            "    public static let id = {RT}.Column<{row}, {RT}.ID>(\"id\")"
        );
        for f in &fields {
            if f.transform.is_some() {
                let _ = writeln!(
                    out,
                    "    /// Column `{}`, as stored: filters compare stored values.",
                    f.column.name
                );
            } else {
                let _ = writeln!(out, "    /// Column `{}`.", f.column.name);
            }
            let _ = writeln!(
                out,
                "    public static let {} = {RT}.Column<{row}, {}>({})",
                f.ident,
                f.stored,
                swift_string(&f.column.name)
            );
        }
        for r in &relations {
            let _ = writeln!(
                out,
                "    /// Relation `{}`, for `include` (narrow it with `where`, `orderBy`, `limit`, `include`).\n    public static let {} = {RT}.Relation<{row}, {}>({})",
                r.name,
                r.ident,
                r.target,
                swift_string(&r.name)
            );
        }
        out.push_str("}\n\n");
        Ok(out)
    }

    /// `JazzApp`'s own members, first: the recorded source, the embedded
    /// file and `open`.
    fn open(&self) -> String {
        let mut out = String::new();
        let hashes = "#".repeat(longest_hash_run(&self.app.file) + 1);
        let mut file = self.app.file.clone();
        if !file.ends_with('\n') {
            file.push('\n');
        }
        out.push_str(
            "    /// `sha256:…` of the `jazz.app.json` these bindings were generated from.\n",
        );
        let _ = writeln!(out, "{SOURCE_PREFIX}{}", swift_string(&self.app.source));
        out.push('\n');
        out.push_str(
            "    /// The app's `jazz.app.json`: its schema, every earlier version and the\n    /// migrations between them.\n",
        );
        let _ = write!(out, "{APP_PREFIX}{hashes}\"\"\"\n{file}\"\"\"{hashes}\n\n");
        out.push_str(
            "    /// Opens the app as an end-user client (`.client(…)`, signed in through\n    /// the app's Jazz endpoint) or a local one (`.local()`).\n",
        );
        if self.has_computed {
            let _ = writeln!(
                out,
                "    public static func open(_ config: {RT}.Config, computed: some Computed) async throws -> {RT}.Client {{\n        try await {RT}.Client.open(app: app, config: config, implementations: computed)\n    }}\n"
            );
        } else {
            let _ = writeln!(
                out,
                "    public static func open(_ config: {RT}.Config) async throws -> {RT}.Client {{\n        try await {RT}.Client.open(app: app, config: config)\n    }}\n"
            );
        }
        out
    }
}

struct Field<'a> {
    column: &'a Column,
    ident: String,
    /// What the row holds: the transform's view type, if it has one.
    ty: String,
    /// What the engine stores.
    stored: String,
    /// The transform's method stem (`isoDate` for `isoDateView`/`isoDateStored`).
    transform: Option<String>,
}

struct RelationField {
    name: String,
    ident: String,
    /// `ident` without backticks.
    bare: String,
    /// The related row type.
    target: String,
    /// A reverse relation, or a forward one through an array of ids.
    to_many: bool,
}

struct ComputedField {
    ident: String,
    ty: String,
    /// Its `JazzApp.Computed` method.
    method: String,
    /// The method's arguments: (label, type).
    args: Vec<(String, String)>,
}

impl Field<'_> {
    /// The stored type without `?`.
    fn stored_inner(&self) -> &str {
        self.stored.strip_suffix('?').unwrap_or(&self.stored)
    }

    /// Decoding the field from a row's container, through its transform.
    fn decode(&self) -> String {
        let key = format!("forKey: .{}", self.ident);
        let inner = self.stored_inner();
        let stored = if self.column.ty.nullable {
            format!("try container.decodeIfPresent({inner}.self, {key})")
        } else {
            format!("try container.decode({inner}.self, {key})")
        };
        match &self.transform {
            None => stored,
            Some(t) if self.column.ty.nullable => {
                format!("({stored}).map {{ computed.{t}View($0) }}")
            }
            Some(t) => format!("computed.{t}View({stored})"),
        }
    }

    /// Encoding the field (of a row, or an insert) into a container.
    fn encode(&self, insert: bool) -> String {
        let key = format!("forKey: .{}", self.ident);
        let optional = self.column.ty.nullable || (insert && self.optional_on_insert());
        let value = match &self.transform {
            None => format!("self.{}", self.ident),
            Some(t) if optional => format!("self.{}.map {{ computed.{t}Stored($0) }}", self.ident),
            Some(t) => format!("computed.{t}Stored(self.{})", self.ident),
        };
        if optional {
            format!("try container.encodeIfPresent({value}, {key})")
        } else {
            format!("try container.encode({value}, {key})")
        }
    }

    fn optional_on_insert(&self) -> bool {
        self.column.optional_on_insert()
    }

    /// Inserts take `nil` for a column with a default, or a nullable one.
    fn insert_type(&self) -> String {
        if self.optional_on_insert() && !self.column.ty.nullable {
            format!("{}?", self.ty)
        } else {
            self.ty.clone()
        }
    }

    fn doc(&self, out: &mut String) {
        if self.ident.trim_matches('`') != self.column.name {
            let _ = writeln!(out, "    /// `{}`.", self.column.name);
        }
    }
}

/// `, a: A, b: B? = nil` for an init: inserts default what they may leave out.
fn params(fields: &[Field<'_>], insert: bool) -> String {
    fields
        .iter()
        .map(|f| {
            if insert {
                let ty = f.insert_type();
                if f.optional_on_insert() {
                    format!(", {}: {ty} = nil", f.ident)
                } else {
                    format!(", {}: {ty}", f.ident)
                }
            } else {
                format!(", {}: {}", f.ident, f.ty)
            }
        })
        .collect()
}

fn coding_keys(out: &mut String, fields: &[Field<'_>], with_id: bool) {
    out.push_str("    enum CodingKeys: Swift.String, Swift.CodingKey {\n");
    if with_id {
        out.push_str("        case id\n");
    }
    for f in fields {
        let _ = writeln!(
            out,
            "        case {} = {}",
            f.ident,
            swift_string(&f.column.name)
        );
    }
    out.push_str("    }\n");
}

/// The `JazzApp.Computed` method of a computed field: `tasksPriority`.
fn computed_method(
    table: &Table,
    computed: &crate::model::Computed,
) -> Result<String, CodegenError> {
    let ident = value_ident(&format!(
        "{}_{}",
        words(&table.name).join("_"),
        words(&computed.name).join("_")
    ))?;
    Ok(ident.trim_matches('`').to_owned())
}

/// A Swift string literal of `text`.
fn swift_string(text: &str) -> String {
    let mut out = String::from("\"");
    for c in text.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 => {
                let _ = write!(out, "\\u{{{:x}}}", c as u32);
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

fn longest_hash_run(text: &str) -> usize {
    text.split(|c| c != '#').map(str::len).max().unwrap_or(0)
}

/// Parses a string literal [`swift_string`] wrote.
fn parse_swift_string(literal: &str) -> Option<String> {
    let body = literal.strip_prefix('"')?.strip_suffix('"')?;
    let mut out = String::new();
    let mut chars = body.chars();
    while let Some(c) = chars.next() {
        if c != '\\' {
            out.push(c);
            continue;
        }
        match chars.next()? {
            '"' => out.push('"'),
            '\\' => out.push('\\'),
            'n' => out.push('\n'),
            'r' => out.push('\r'),
            't' => out.push('\t'),
            'u' => {
                let rest: String = chars.by_ref().take_while(|c| *c != '}').collect();
                let hex = rest.strip_prefix('{')?;
                out.push(char::from_u32(u32::from_str_radix(hex, 16).ok()?)?);
            }
            _ => return None,
        }
    }
    Some(out)
}

pub(crate) fn read(bindings: &str) -> Result<crate::bindings::Recorded, CodegenError> {
    let refuse = |what: &str| {
        CodegenError::new(format!(
            "{FILE}: {what}; regenerate it with `jazz-tools generate`"
        ))
    };
    let bindings = bindings.strip_prefix('\u{feff}').unwrap_or(bindings);
    let mut lines = bindings.lines();
    if !matches!(lines.next(), Some(HEADER | LEGACY_HEADER)) {
        return Err(refuse(
            "not a file jazz-tools generated (its first line differs)",
        ));
    }
    let format = lines
        .next()
        .and_then(|line| line.strip_prefix(FORMAT_PREFIX))
        .and_then(|rest| rest.split('.').next())
        .and_then(|n| n.parse::<u32>().ok())
        .ok_or_else(|| refuse("no `// Bindings format <n>.` second line"))?;
    // Only `JazzApp` holds them: a table's namespace may have columns named
    // `source` or `app`.
    let start = bindings
        .find(JAZZ_APP_OPEN)
        .ok_or_else(|| refuse("no `public enum JazzApp`"))?;
    let bindings = &bindings[start..];
    let source = bindings
        .lines()
        .find_map(|line| line.strip_prefix(SOURCE_PREFIX))
        .and_then(|literal| parse_swift_string(literal.trim_end()))
        .ok_or_else(|| refuse("no `public static let source`"))?;
    let at = bindings
        .find(APP_PREFIX)
        .ok_or_else(|| refuse("no `public static let app`"))?
        + APP_PREFIX.len();
    let rest = &bindings[at..];
    let hashes = rest.chars().take_while(|c| *c == '#').count();
    let open = format!("{}\"\"\"\n", "#".repeat(hashes));
    let close = format!("\n\"\"\"{}", "#".repeat(hashes));
    let file = rest
        .strip_prefix(&open)
        .and_then(|body| body.find(&close).map(|end| &body[..end + 1]))
        .ok_or_else(|| refuse("`app` is cut short"))?;
    let unusable = |what: &str| {
        CodegenError::new(format!(
            "{FILE}: {what}. Restore it from version control; or delete it and run \
             `jazz-tools generate` (an edit of `tables` since it was generated then \
             has no recorded version to migrate from)"
        ))
    };
    if jazz::tools::deployment::artifact::source_hash(file.as_bytes()) != source {
        return Err(unusable(
            "its `app` was edited (it no longer matches `source`)",
        ));
    }
    let app = App::load(file.as_bytes())
        .map_err(|error| unusable(&format!("its `app` no longer loads ({error})")))?;
    Ok(crate::bindings::Recorded {
        source,
        format,
        current: app.compiled.current,
        current_schema: app.compiled.current_schema().clone(),
    })
}

