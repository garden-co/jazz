# Generates tables.rs (the analyzer `jazz-text/1`'s character tables, SPEC
# 20.10.1: segmentation classes, case folding, `jazz-text/fold/1`) from Unicode 16.0.0: CaseFolding.txt and Python's unicodedata,
# which must be 16.0.0 (Python 3.14). Run from this directory:
#
#   curl -O https://www.unicode.org/Public/16.0.0/ucd/CaseFolding.txt
#   python3 -I gen_tables.py CaseFolding.txt > tables.rs
#
# Any change to the output is a new analyzer version (INV-IX-5).
import sys, unicodedata as u
assert u.unidata_version == "16.0.0"
cf = {}
for line in open(sys.argv[1]):
    line = line.split('#')[0].strip()
    if not line: continue
    code, status, mapping = [x.strip() for x in line.split(';')[:3]]
    if status in ('C', 'S'):
        cf[int(code, 16)] = int(mapping, 16)
def fold1(c): return cf.get(c, c)
# runs of (lo, hi, delta, stride)
items = sorted(cf.items())
runs = []
for c, m in items:
    d = m - c
    if runs:
        lo, hi, dd, st = runs[-1]
        if dd == d and ((st in (0, 1) and c == hi + 1) or (st in (0, 2) and c == hi + 2)):
            st = st or (c - hi)
            runs[-1] = (lo, c, d, st); continue
    runs.append((c, c, d, 0))
# diacritic fold
blocks = [(0x00C0,0x024F),(0x1E00,0x1EFF),(0x2C60,0x2C7F),(0xA720,0xA7FF),(0x0370,0x03FF),(0x1F00,0x1FFF),(0x0400,0x052F)]
extra = {'ß':'ss','æ':'ae','œ':'oe','ø':'o','ł':'l','đ':'d','ħ':'h','ŀ':'l','ı':'i','ĳ':'ij','ŧ':'t','ƀ':'b'}
fold = {}
for lo, hi in blocks:
    for c in range(lo, hi + 1):
        ch = chr(c)
        if u.category(ch)[0] != 'L' or fold1(c) != c: continue
        d = ''.join(x for x in u.normalize('NFD', ch) if not 0x300 <= ord(x) <= 0x36F)
        d = ''.join(chr(fold1(ord(x))) for x in d)
        d = extra.get(ch) or ''.join(extra.get(x, x) for x in d)
        if d != ch and d and all(u.category(x)[0] == 'L' for x in d):
            fold[c] = d
for k in extra: assert ord(k) in fold, k
# Compatibility forms typed in place of Latin letters and digits: the
# Latin ligatures and the fullwidth forms, by compatibility decomposition.
for lo, hi in [(0xFB00, 0xFB06), (0xFF10, 0xFF19), (0xFF41, 0xFF5A)]:
    for c in range(lo, hi + 1):
        d = u.normalize('NFKD', chr(c))
        assert d.isascii() and d.isalnum(), hex(c)
        fold[c] = d
one = sorted((c, d) for c, d in fold.items() if len(d) == 1)
many = sorted((c, d) for c, d in fold.items() if len(d) > 1)
o = []
o.append("// @generated by src/text/gen_tables.py from Unicode 16.0.0. Do not edit.\n// Changing any table is a new analyzer version (SPEC 20.2, INV-IX-5).\n")
o.append("/// Unicode 16.0.0 simple case folding (CaseFolding.txt, status C and S), as\n/// runs: every `stride`-th code point from `first` to `first + span` maps to\n/// itself plus `delta`. Packed as `(first | (stride == 2) << 31,\n/// span << 20 | delta as 20-bit two's complement)`.")
o.append("#[rustfmt::skip]\npub(super) const CASE_FOLD: &[(u32, u32)] = &[")
for lo, hi, d, st in runs:
    assert lo < 1 << 21 and hi - lo < 1 << 12 and -(1 << 19) <= d < 1 << 19
    o.append(f"    (0x{lo | ((st == 2) << 31):08X}, 0x{((hi - lo) << 20) | (d & 0xFFFFF):08X}), // U+{lo:04X}..U+{hi:04X} {d:+} /{st or 1}")
o.append("];\n")
o.append("/// `jazz-text/fold/1`, one-character results: a case-folded Latin, Greek or\n/// Cyrillic letter and its base letter (its canonical decomposition without\n/// U+0300..U+036F marks, case-folded), and fullwidth Latin letters and\n/// digits and their ASCII forms.")
o.append("#[rustfmt::skip]\npub(super) const FOLD_ONE: &[(u16, u16)] = &[")
for i in range(0, len(one), 6): o.append("    " + " ".join(f"(0x{c:04X}, 0x{ord(d):04X})," for c, d in one[i:i+6]))
o.append("];\n")
o.append("/// `jazz-text/fold/1`, longer results: ligatures and `ß`.")
o.append("#[rustfmt::skip]\npub(super) const FOLD_MANY: &[(u16, &str)] = &[")
for c, d in many: o.append(f"    (0x{c:04X}, \"{d}\"), // {chr(c)}")
o.append("];\n")
# Character classes for segmentation (step 1). Frozen with the analyzer,
# independent of jazz-text's merge tokenizer.
SEP, WORD, MARK, ALONE, IGNORE = range(5)
# Ignored inside a word: soft hyphen, zero-width (non-)joiner, word joiner,
# byte order mark.
IGNORED = {0x00AD, 0x200C, 0x200D, 0x2060, 0xFEFF}
# Blocks of the scripts written without spaces between words: their letters
# and digits are words of one character each.
UNSPACED = [(0x0E00, 0x0FFF), (0x1000, 0x109F), (0x1780, 0x17FF), (0x2E80, 0x2FDF),
            (0x3000, 0x31FF), (0x3400, 0x4DBF), (0x4E00, 0x9FFF), (0xA000, 0xA4CF),
            (0xF900, 0xFAFF), (0xFF66, 0xFF9F), (0x20000, 0x3FFFF)]
def cls(c):
    if 0xD800 <= c < 0xE000: return SEP
    if c in IGNORED: return IGNORE
    g = u.category(chr(c))
    if g == 'Cn': return WORD
    unspaced = any(lo <= c <= hi for lo, hi in UNSPACED)
    if g[0] == 'M':
        # A mark completes the character before it: in the unspaced scripts
        # it stays with its standalone letter; elsewhere it is part of a word.
        return MARK if unspaced else WORD
    if g[0] == 'L' or g in ('Nd', 'Nl'):
        return ALONE if unspaced else WORD
    return SEP
bounds = []
prev = None
for c in range(0x110000):
    k = cls(c)
    if k != prev:
        bounds.append((c, k)); prev = k
o.append("/// Character classes for segmentation (Unicode 16.0.0), as the first code\n/// point of each run packed with its class: `first << 3 | class`, class\n/// 0 separator, 1 word, 2 mark, 3 standalone letter, 4 ignored.")
o.append("#[rustfmt::skip]\npub(super) const CLASSES: &[u32] = &[")
for i in range(0, len(bounds), 6): o.append("    " + " ".join(f"0x{(c << 3) | k:08X}," for c, k in bounds[i:i+6]))
o.append("];")
print("\n".join(o))
print(len(runs), len(one), len(many), len(bounds), file=sys.stderr)
# The digest and counts `segmentation_classes_are_pinned` asserts.
h, counts = 0xcbf29ce484222325, [0] * 5
for c in range(0x110000):
    if 0xD800 <= c < 0xE000: continue
    k = cls(c); counts[k] += 1
    h = ((h ^ k) * 0x100000001b3) & 0xFFFFFFFFFFFFFFFF
print(f"classes digest 0x{h:016x} counts {counts}", file=sys.stderr)
