/// Unpack a gzip-compressed RocksDB candidate into a fresh root.  This is kept
/// separate from base64/checksum admission so the producer can prove its
/// newly-exported archive, not just the pinned checked-in artifact.
fn unpack_native_rocksdb_archive(
    root: &std::path::Path,
    archive_bytes: &[u8],
) -> Result<std::path::PathBuf, String> {
    let decoder = flate2::read::GzDecoder::new(std::io::Cursor::new(archive_bytes));
    tar::Archive::new(decoder)
        .unpack(root)
        .map_err(|error| format!("native RocksDB corpus archive is not safe: {error}"))?;
    let database = root.join("rocksdb-epoch-1");
    if !database.is_dir() {
        return Err("native RocksDB corpus archive does not contain rocksdb-epoch-1 root".to_owned());
    }
    Ok(database)
}

fn inspect_native_sqlite_candidate(path: &std::path::Path) -> Result<(), String> {
    let connection = rusqlite::Connection::open_with_flags(
        path,
        rusqlite::OpenFlags::SQLITE_OPEN_READ_ONLY,
    )
    .map_err(|error| format!("candidate SQLite image cannot open read-only: {error}"))?;
    let rows: u64 = connection
        .query_row("SELECT COUNT(*) FROM kv", [], |row| row.get(0))
        .map_err(|error| format!("candidate SQLite image lacks readable kv rows: {error}"))?;
    if rows == 0 {
        return Err("candidate SQLite image has no durable rows".to_owned());
    }
    Ok(())
}

fn inspect_native_rocksdb_candidate(path: &std::path::Path) -> Result<(), String> {
    let options = rocksdb::Options::default();
    let families = rocksdb::DB::list_cf(&options, path)
        .map_err(|error| format!("candidate RocksDB root cannot list column families: {error}"))?;
    let read_only = rocksdb::DB::open_cf_for_read_only(&options, path, &families, false)
        .map_err(|error| format!("candidate RocksDB root cannot open read-only: {error}"))?;
    let rows = families
        .iter()
        .filter_map(|family| read_only.cf_handle(family))
        .map(|family| {
            read_only
                .iterator_cf(family, rocksdb::IteratorMode::Start)
                .count()
        })
        .sum::<usize>();
    if rows == 0 {
        return Err("candidate RocksDB root has no durable rows".to_owned());
    }
    Ok(())
}

/// A regeneration request is intentionally a two-phase operation.  The live
/// producer is only a source for a private staged candidate; an externally
/// requested artifact is not made visible until that candidate has passed the
/// independent fresh-root compatibility receipt.
fn assert_native_corpus_candidate_is_staged(
    live: &std::path::Path,
    candidate: &std::path::Path,
    kind: &str,
) {
    assert!(candidate.exists(), "{kind} staged candidate must exist");
    assert_staged_path_is_distinct(live, candidate, kind)
        .unwrap_or_else(|error| panic!("{kind} candidate must be staged outside the live producer root: {error}"));
}

/// Resolve a corpus file through its existing parent.  Candidates are required
/// to be direct children of an existing staging directory: that makes a path
/// which has not been created yet just as checkable as one which has, while
/// still resolving `.` and symlink aliases in the parent before any bytes are
/// written.
fn canonical_corpus_child(path: &std::path::Path, role: &str) -> Result<std::path::PathBuf, String> {
    let name = path
        .file_name()
        .filter(|name| !name.is_empty())
        .ok_or_else(|| format!("{role} must name a file directly below an existing directory"))?;
    let parent = path
        .parent()
        .filter(|parent| !parent.as_os_str().is_empty())
        .ok_or_else(|| format!("{role} must have an existing parent directory"))?;
    let canonical_parent = std::fs::canonicalize(parent)
        .map_err(|error| format!("cannot resolve {role} parent {parent:?}: {error}"))?;
    if !canonical_parent.is_dir() {
        return Err(format!("{role} parent {canonical_parent:?} is not a directory"));
    }
    Ok(canonical_parent.join(name))
}

/// Create an implementation-owned staging root.  Regeneration accepts a
/// maintainer-selected *publication* path, but never a staging path: the
/// source database must first be copied into a private, independent location
/// before the fresh-root receipt is allowed to inspect it.
fn private_native_corpus_staging_root(kind: &str) -> tempfile::TempDir {
    tempfile::Builder::new()
        .prefix(&format!("jazz-native-corpus-{kind}-staging-"))
        .tempdir()
        .expect("create private native corpus staging root")
}

fn path_entry_exists(path: &std::path::Path) -> Result<bool, String> {
    match std::fs::symlink_metadata(path) {
        Ok(_) => Ok(true),
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok(false),
        Err(error) => Err(format!("cannot inspect corpus path {path:?}: {error}")),
    }
}

fn same_existing_file_identity(
    left: &std::path::Path,
    right: &std::path::Path,
) -> Result<bool, String> {
    let left_metadata = std::fs::metadata(left)
        .map_err(|error| format!("cannot stat left corpus path {left:?}: {error}"))?;
    let right_metadata = std::fs::metadata(right)
        .map_err(|error| format!("cannot stat right corpus path {right:?}: {error}"))?;

    #[cfg(unix)]
    {
        use std::os::unix::fs::MetadataExt as _;
        return Ok(left_metadata.dev() == right_metadata.dev() && left_metadata.ino() == right_metadata.ino());
    }
    #[cfg(windows)]
    {
        use std::os::windows::fs::MetadataExt as _;
        return Ok(
            left_metadata.volume_serial_number() == right_metadata.volume_serial_number()
                && left_metadata.file_index_high() == right_metadata.file_index_high()
                && left_metadata.file_index_low() == right_metadata.file_index_low(),
        );
    }
    #[cfg(not(any(unix, windows)))]
    {
        // A platform without a stable file identity cannot prove hard-link
        // separation.  Canonical paths still reject dot and symlink aliases;
        // callers additionally reject the same canonical path below.
        let _ = (left_metadata, right_metadata);
        Ok(false)
    }
}

/// Return every regular member of a live store.  SQLite contributes its one
/// image; RocksDB contributes its manifest, logs, SSTs, and any other regular
/// backend-owned members.  Symlinks are deliberately not followed: this is a
/// trusted-maintainer accidental-alias guard, not an attempt to make a
/// concurrent hostile filesystem namespace safe against TOCTOU replacement.
fn regular_files_below(path: &std::path::Path) -> Result<Vec<std::path::PathBuf>, String> {
    let metadata = std::fs::symlink_metadata(path)
        .map_err(|error| format!("cannot inspect corpus path {path:?}: {error}"))?;
    if metadata.file_type().is_symlink() {
        return Err(format!("corpus path {path:?} is a symlink"));
    }
    if metadata.is_file() {
        return Ok(vec![path.to_path_buf()]);
    }
    if !metadata.is_dir() {
        return Ok(Vec::new());
    }

    let mut files = Vec::new();
    for entry in std::fs::read_dir(path)
        .map_err(|error| format!("cannot list corpus directory {path:?}: {error}"))?
    {
        let entry = entry.map_err(|error| format!("cannot read corpus directory entry: {error}"))?;
        let child = entry.path();
        let child_metadata = std::fs::symlink_metadata(&child)
            .map_err(|error| format!("cannot inspect corpus member {child:?}: {error}"))?;
        if child_metadata.file_type().is_symlink() {
            return Err(format!("corpus member {child:?} is a symlink"));
        }
        if child_metadata.is_file() {
            files.push(child);
        } else if child_metadata.is_dir() {
            files.extend(regular_files_below(&child)?);
        }
    }
    Ok(files)
}

/// A staged file must not share physical identity with *any* regular member of
/// the live store.  Checking only the live root misses the dangerous RocksDB
/// case where a candidate entry aliases an SST or MANIFEST directly.
fn assert_candidate_regular_files_are_independent(
    live: &std::path::Path,
    candidate: &std::path::Path,
    kind: &str,
) -> Result<(), String> {
    if !path_entry_exists(candidate)? {
        return Ok(());
    }
    let live_files = regular_files_below(live)?;
    let candidate_files = regular_files_below(candidate)?;
    for candidate_file in &candidate_files {
        for live_file in &live_files {
            if same_existing_file_identity(live_file, candidate_file)? {
                return Err(format!(
                    "{kind} candidate file {candidate_file:?} is physically linked to live producer member {live_file:?}"
                ));
            }
        }
    }
    Ok(())
}

/// Prove a staged candidate cannot be the live producer through spelling,
/// symlink, or (on platforms that expose one) physical-file aliasing.  `live`
/// is a SQLite file or a RocksDB root/archive source; candidates may be absent
/// when this is used to vet a not-yet-created temporary publication path.
fn assert_staged_path_is_distinct(
    live: &std::path::Path,
    candidate: &std::path::Path,
    kind: &str,
) -> Result<(), String> {
    let live_canonical = std::fs::canonicalize(live)
        .map_err(|error| format!("cannot resolve live {kind} producer {live:?}: {error}"))?;
    let live_root = if live_canonical.is_dir() {
        live_canonical.clone()
    } else {
        live_canonical
            .parent()
            .ok_or_else(|| format!("live {kind} producer has no parent"))?
            .to_path_buf()
    };
    let candidate_canonical = canonical_corpus_child(candidate, &format!("{kind} candidate"))?;

    if candidate_canonical == live_canonical
        || candidate_canonical.starts_with(&live_root)
    {
        return Err(format!(
            "candidate {candidate:?} resolves inside live producer root {live_root:?}"
        ));
    }
    if path_entry_exists(candidate)? {
        let candidate_metadata = std::fs::symlink_metadata(candidate)
            .map_err(|error| format!("cannot inspect existing {kind} candidate {candidate:?}: {error}"))?;
        if candidate_metadata.file_type().is_symlink() {
            return Err(format!("candidate {candidate:?} is a symlink"));
        }
        let candidate_target = std::fs::canonicalize(candidate)
            .map_err(|error| format!("cannot resolve existing {kind} candidate {candidate:?}: {error}"))?;
        if candidate_target == live_canonical || candidate_target.starts_with(&live_root) {
            return Err(format!(
                "candidate {candidate:?} resolves through an alias inside live producer root {live_root:?}"
            ));
        }
    }
    assert_candidate_regular_files_are_independent(live, candidate, kind)?;
    Ok(())
}

/// A candidate and publication destination must not alias, even where their
/// textual paths differ.  This protects an existing destination from being
/// silently used as the source and makes a future temporary name checkable
/// before it exists.
fn assert_publication_paths_are_distinct(
    candidate: &std::path::Path,
    requested: &std::path::Path,
) -> Result<(std::path::PathBuf, std::path::PathBuf), String> {
    let candidate_canonical = canonical_corpus_child(candidate, "corpus candidate")?;
    let requested_canonical = canonical_corpus_child(requested, "requested corpus output")?;
    if candidate_canonical == requested_canonical {
        return Err("requested corpus output aliases its staged candidate".to_owned());
    }
    if path_entry_exists(requested)? {
        return Err("requested corpus output already exists; choose a new path or delete it before regeneration".to_owned());
    }
    Ok((candidate_canonical, requested_canonical))
}

/// Publish a *previously verified* candidate without exposing a partially
/// copied output.  This deliberately does not validate the candidate itself:
/// callers must run the semantic verifier first, which keeps the publication
/// boundary obvious in the regeneration receipt.
fn publish_verified_native_corpus_candidate(
    candidate: &std::path::Path,
    requested: &std::path::Path,
) -> Result<(), String> {
    publish_verified_native_corpus_candidate_with_copy(candidate, requested, |candidate, temporary| {
        std::fs::copy(candidate, temporary)
            .map(|_| ())
            .map_err(|error| error.to_string())
    })
}

/// The copy operation is an explicit seam so this receipt can prove that an
/// interrupted staged copy never touches a pre-existing destination.  The
/// normal publisher above supplies `std::fs::copy`; no production path may
/// write directly to `requested` before the staged copy has completed.
fn publish_verified_native_corpus_candidate_with_copy(
    candidate: &std::path::Path,
    requested: &std::path::Path,
    copy: impl FnOnce(&std::path::Path, &std::path::Path) -> Result<(), String>,
) -> Result<(), String> {
    let (candidate, requested) = assert_publication_paths_are_distinct(candidate, requested)?;
    let parent = requested.parent().expect("canonical child has a parent");
    let file_name = requested.file_name().expect("canonical child has a name");
    let temporary = parent.join(format!(
        ".{}.native-corpus-staging-{}",
        file_name.to_string_lossy(),
        uuid::Uuid::new_v4()
    ));
    // Reserve the private name before copying.  It lives next to the requested
    // output so a later hard-link publication is an atomic create-new operation
    // on one filesystem; an existing output, including a dangling symlink, is
    // always rejected above and never overwritten.
    std::fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(&temporary)
        .map_err(|error| format!("reserve private corpus publication path {temporary:?}: {error}"))?;
    if let Err(error) = copy(&candidate, &temporary) {
        let _ = std::fs::remove_file(&temporary);
        return Err(error);
    }
    std::fs::hard_link(&temporary, &requested).map_err(|error| {
        let _ = std::fs::remove_file(&temporary);
        format!("publish verified corpus without overwriting {requested:?}: {error}")
    })?;
    std::fs::remove_file(&temporary)
        .map_err(|error| format!("remove private corpus staging file {temporary:?}: {error}"))
}

/// Keep failed admissions from accidentally reaching the requested path.  The
/// production receipt uses the same sequencing explicitly around its full
/// semantic verifier; this smaller helper lets planted corrupt candidates
/// prove the publication guard without constructing a full producer.
fn verify_then_publish_native_corpus_candidate(
    verify: impl FnOnce() -> Result<(), String>,
    candidate: &std::path::Path,
    requested: &std::path::Path,
) -> Result<(), String> {
    verify()?;
    publish_verified_native_corpus_candidate(candidate, requested)
}

fn assert_same_native_corpus(
    left: &NativeCorpusReceipt,
    right: &NativeCorpusReceipt,
    message: &str,
) {
    if left == right {
        return;
    }
    let differing_store = left
        .stores
        .keys()
        .chain(right.stores.keys())
        .find(|store| left.stores.get(*store) != right.stores.get(*store));
    panic!(
        "{message}; first differing store={differing_store:?}, left checksum={}, right checksum={}",
        native_corpus_checksum(left),
        native_corpus_checksum(right),
    );
}

/// Return the engine-owned metadata ledger from Groove's shared large-value
/// class. `chunk/` entries are the backing chunk plane's bytes and its local
/// installation receipt; their physical representation is backend-owned.
/// Every other key prefix is a canonical Groove metadata/lifecycle record and
/// is therefore part of the backend-neutral historical pack. Unknown keys
/// fail closed rather than disappearing from the corpus when that ledger
/// grows.
fn native_corpus_large_value_metadata_entries<S>(node: &NodeState<S>) -> Vec<(Vec<u8>, Vec<u8>)>
where
    S: OrderedKvStorage,
{
    let entries = crate::db::block_on(
        node.database
            .large_value_metadata_entries_for_compatibility(),
    )
    .expect("scan Groove large-value metadata corpus family");
    let metadata_prefixes: &[&[u8]] = &[
        b"root/",
        b"node/",
        b"reclaim/",
        b"staged/",
        b"upload/",
        b"completed-upload/",
        b"completed-receipt/",
        b"install/",
    ];
    entries
        .into_iter()
        .filter_map(|(key, value)| {
            if key.starts_with(b"chunk/") {
                return None;
            }
            assert!(
                metadata_prefixes.iter().any(|prefix| key.starts_with(prefix)),
                "unknown key in Groove large-value metadata family must be explicitly classified before corpus publication: {}",
                hex::encode(&key),
            );
            Some((key, value))
        })
        .collect()
}

