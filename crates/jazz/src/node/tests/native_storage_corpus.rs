fn decode_native_corpus_pack(base64: &str, expected_sha256: &str, name: &str) -> String {
    let bytes = STANDARD
        .decode(base64.trim())
        .expect("native corpus pack must be base64");
    assert_eq!(
        format!("{:x}", Sha256::digest(&bytes)),
        expected_sha256,
        "{name} checksum must match before it is compared"
    );
    let pack = String::from_utf8(bytes).expect("native corpus pack must be UTF-8");
    assert!(
        pack.starts_with(&format!("{NATIVE_CORPUS_PACK_HEADER}\n")),
        "{name} must retain its exact epoch header"
    );
    pack
}

fn decode_native_physical_fixture(
    base64: &str,
    expected_sha256: &str,
    family: &str,
) -> Result<Vec<u8>, String> {
    let bytes = STANDARD
        .decode(base64.lines().collect::<String>())
        .map_err(|error| format!("{family} corpus fixture is not base64: {error}"))?;
    if format!("{:x}", Sha256::digest(&bytes)) != expected_sha256 {
        return Err(format!("{family} corpus fixture checksum does not match"));
    }
    Ok(bytes)
}

fn materialize_native_sqlite_fixture(path: &std::path::Path, base64: &str) -> Result<(), String> {
    materialize_native_sqlite_fixture_with_hashes(path, base64, EPOCH_1_NATIVE_SQLITE_ARCHIVE_SHA256, EPOCH_1_NATIVE_SQLITE_SHA256)
}

fn materialize_native_sqlite_fixture_with_hashes(path: &std::path::Path, base64: &str, archive_sha: &str, sqlite_sha: &str) -> Result<(), String> {
    // Verify the immutable payload before creating a target. This is both a
    // corruption receipt and a guard against a bad checked-in fixture being
    // reported later as an adapter-open failure.
    let bytes = decode_native_physical_fixture(
        base64,
        archive_sha,
        "SQLite",
    )?;
    let mut sqlite = Vec::new();
    std::io::Read::read_to_end(
        &mut flate2::read::GzDecoder::new(std::io::Cursor::new(bytes)),
        &mut sqlite,
    )
    .map_err(|error| format!("SQLite corpus fixture is not gzip: {error}"))?;
    if format!("{:x}", Sha256::digest(&sqlite)) != sqlite_sha {
        return Err("SQLite corpus decompressed checksum does not match".to_owned());
    }
    materialize_native_sqlite_bytes(path, &sqlite)
}

/// Materialize an already validated SQLite image at a new physical location.
///
/// The producer uses this independently of its live database: a candidate is
/// only useful as a future historical fixture if a fresh process can open the
/// copied bytes, rather than if the still-open producer root happens to work.
fn materialize_native_sqlite_bytes(path: &std::path::Path, sqlite: &[u8]) -> Result<(), String> {
    std::fs::write(path, sqlite).map_err(|error| error.to_string())
}

