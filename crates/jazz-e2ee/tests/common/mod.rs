#![allow(dead_code)]

use jazz_e2ee::{Error, RandomSource, Result};

pub fn hex(value: &str) -> Vec<u8> {
    assert!(value.len().is_multiple_of(2), "odd hex length");
    (0..value.len())
        .step_by(2)
        .map(|at| u8::from_str_radix(&value[at..at + 2], 16).expect("hex digit"))
        .collect()
}

pub fn to_hex(bytes: &[u8]) -> String {
    bytes.iter().map(|byte| format!("{byte:02x}")).collect()
}

pub fn array<const N: usize>(value: &str) -> [u8; N] {
    hex(value).try_into().expect("vector length")
}

/// Yields the given bytes in order, then fails.
pub struct FixedRandom(pub Vec<u8>);

impl RandomSource for FixedRandom {
    fn fill(&mut self, dest: &mut [u8]) -> Result<()> {
        if self.0.len() < dest.len() {
            return Err(Error::RandomUnavailable);
        }
        dest.copy_from_slice(&self.0[..dest.len()]);
        self.0.drain(..dest.len());
        Ok(())
    }
}

/// A fast deterministic generator (xorshift64*) for test inputs only.
pub struct TestRandom(pub u64);

impl TestRandom {
    pub fn next_u64(&mut self) -> u64 {
        self.0 ^= self.0 >> 12;
        self.0 ^= self.0 << 25;
        self.0 ^= self.0 >> 27;
        self.0.wrapping_mul(0x2545_f491_4f6c_dd1d)
    }

    pub fn below(&mut self, bound: usize) -> usize {
        (self.next_u64() % bound as u64) as usize
    }

    pub fn bytes(&mut self, length: usize) -> Vec<u8> {
        let mut bytes = vec![0; length];
        self.fill(&mut bytes).expect("infallible");
        bytes
    }

    /// Up to `max - 1` random bytes.
    pub fn sized(&mut self, max: usize) -> Vec<u8> {
        let length = self.below(max);
        self.bytes(length)
    }

    /// Flips one random bit.
    pub fn flip(&mut self, bytes: &mut [u8]) {
        let at = self.below(bytes.len());
        bytes[at] ^= 1 << self.below(8);
    }

    pub fn array<const N: usize>(&mut self) -> [u8; N] {
        self.bytes(N).try_into().expect("length")
    }
}

impl RandomSource for TestRandom {
    fn fill(&mut self, dest: &mut [u8]) -> Result<()> {
        for chunk in dest.chunks_mut(8) {
            let value = self.next_u64().to_le_bytes();
            chunk.copy_from_slice(&value[..chunk.len()]);
        }
        Ok(())
    }
}

