#!/usr/bin/env node
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(fileURLToPath(new URL("../..", import.meta.url)));
const read = (path) => JSON.parse(readFileSync(path, "utf8"));
const wasm = read(join(root, "crates/jazz-wasm/pkg/.jazz-artifact-manifest.json"));
const napi = read(join(root, "crates/jazz-napi/provenance/jazz-napi.linux-x64-gnu.manifest.json"));
for (const [name, manifest] of [
  ["wasm", wasm],
  ["napi", napi],
])
  if (!/^[a-f0-9]{64}$/.test(manifest.nativeArtifactFingerprint ?? ""))
    throw new Error(`${name} manifest lacks a native fingerprint`);
const runtime = join(root, "packages/jazz-tools/src/runtime");
writeFileSync(
  join(runtime, "native-artifact-fingerprint-napi.ts"),
  `// Generated by release assembly.\nexport const EXPECTED_NAPI_ARTIFACT_FINGERPRINT = ${JSON.stringify(napi.nativeArtifactFingerprint)} as const;\n`,
);
writeFileSync(
  join(runtime, "native-artifact-fingerprint-wasm.ts"),
  `// Generated by release assembly.\nexport const EXPECTED_WASM_ARTIFACT_FINGERPRINT = ${JSON.stringify(wasm.nativeArtifactFingerprint)} as const;\n`,
);
