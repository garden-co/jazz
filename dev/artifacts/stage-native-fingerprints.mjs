#!/usr/bin/env node
import { createHash } from "node:crypto";
import { existsSync, lstatSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const read = (path) => JSON.parse(readFileSync(path, "utf8"));
const wasmArtifactFiles = [
  "jazz_wasm_bg.wasm",
  "jazz_wasm_bg.wasm.d.ts",
  "jazz_wasm.d.ts",
  "jazz_wasm.js",
];
export function stageNativeFingerprints(root, { local = false } = {}) {
  const wasm = read(join(root, "crates/jazz-wasm/pkg/.jazz-artifact-manifest.json"));
  const napi = local
    ? read(
        join(
          root,
          "crates/jazz-napi/.native-artifacts",
          /generation-[A-Za-z0-9.-]+/.exec(
            readFileSync(join(root, "crates/jazz-napi/native-binding.pointer.cjs"), "utf8"),
          )?.[0] ?? "missing",
          ".jazz-artifact-manifest.json",
        ),
      )
    : read(join(root, "crates/jazz-napi/provenance/jazz-napi.linux-x64-gnu.manifest.json"));
  for (const [name, manifest] of [
    ["wasm", wasm],
    ["napi", napi],
  ])
    if (!/^[a-f0-9]{64}$/.test(manifest.nativeArtifactFingerprint ?? ""))
      throw new Error(`${name} manifest lacks a native fingerprint`);
  if (wasm.kind !== "wasm" || wasm.profile !== (local ? "fast" : "release"))
    throw new Error("downloaded WASM manifest has the wrong kind/profile");
  const artifacts = wasm.artifacts;
  if (!Array.isArray(artifacts) || artifacts.length !== wasmArtifactFiles.length)
    throw new Error("downloaded WASM manifest must list each generated artifact exactly once");
  const artifactNames = artifacts.map((artifact) => artifact?.file);
  if (
    new Set(artifactNames).size !== wasmArtifactFiles.length ||
    wasmArtifactFiles.some((file) => !artifactNames.includes(file))
  )
    throw new Error("downloaded WASM manifest must list each generated artifact exactly once");
  for (const artifact of artifacts) {
    if (!artifact || typeof artifact.file !== "string")
      throw new Error("downloaded WASM manifest has an invalid artifact entry");
    const path = join(root, "crates/jazz-wasm/pkg", artifact.file);
    const hash =
      existsSync(path) &&
      lstatSync(path).isFile() &&
      lstatSync(path).size > 0 &&
      /^[a-f0-9]{64}$/.test(artifact.sha256 ?? "") &&
      createHash("sha256").update(readFileSync(path)).digest("hex");
    if (hash !== artifact.sha256)
      throw new Error(`downloaded WASM artifact hash mismatch: ${artifact.file}`);
  }
  if (napi.kind !== "napi" || napi.profile !== "release")
    throw new Error("downloaded NAPI manifest has the wrong kind/profile");
  const runtime = join(root, "packages/jazz-tools/src/runtime");
  const fingerprintSource = (name, fingerprint) =>
    `// Generated by release assembly.\nexport const ${name} =\n  ${JSON.stringify(fingerprint)} as const;\n`;
  writeFileSync(
    join(runtime, "native-artifact-fingerprint-napi.ts"),
    fingerprintSource("EXPECTED_NAPI_ARTIFACT_FINGERPRINT", napi.nativeArtifactFingerprint),
  );
  writeFileSync(
    join(runtime, "native-artifact-fingerprint-wasm.ts"),
    fingerprintSource("EXPECTED_WASM_ARTIFACT_FINGERPRINT", wasm.nativeArtifactFingerprint),
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = resolve(fileURLToPath(new URL("../..", import.meta.url)));
  try {
    stageNativeFingerprints(root, { local: process.argv.includes("--local") });
  } catch (error) {
    console.error(`stage native fingerprints: ${error.message}`);
    process.exitCode = 1;
  }
}
