#!/usr/bin/env node
import { createHash } from "node:crypto";
import { existsSync, lstatSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const read = (path) => JSON.parse(readFileSync(path, "utf8"));
// The one place the local build hint lives; native-inputs.mjs and README
// point here rather than repeating the steps.
export const localBuildHint =
  "Run `pnpm --filter jazz-tools build:runtime`, which builds any missing native inputs for " +
  "this host (Linux x64/arm64, macOS) and stages them with --workspace.";
const readManifest = (root, path, what) => {
  if (!existsSync(join(root, path)))
    throw new Error(`${what} is missing (${path}). ${localBuildHint}`);
  return read(join(root, path));
};
const wasmArtifactFiles = [
  "jazz_wasm_bg.wasm",
  "jazz_wasm_bg.wasm.d.ts",
  "jazz_wasm.d.ts",
  "jazz_wasm.js",
];
export function stageNativeFingerprints(
  root,
  { local = false, workspace = false, profiling = false } = {},
) {
  if ([local, workspace, profiling].filter(Boolean).length > 1)
    throw new Error("--local, --workspace and --profiling are mutually exclusive");
  const wasm = readManifest(
    root,
    "crates/jazz-wasm/pkg/.jazz-artifact-manifest.json",
    "the jazz-wasm build manifest",
  );
  let napi;
  if (local || workspace || profiling) {
    const pointer = "crates/jazz-napi/native-binding.pointer.cjs";
    if (!existsSync(join(root, pointer)))
      throw new Error(`the jazz-napi build pointer is missing (${pointer}). ${localBuildHint}`);
    const generation = /generation-[A-Za-z0-9.-]+/.exec(
      readFileSync(join(root, pointer), "utf8"),
    )?.[0];
    if (!generation)
      throw new Error(
        `the jazz-napi build pointer names no generation (${pointer}). ${localBuildHint}`,
      );
    napi = readManifest(
      root,
      `crates/jazz-napi/.native-artifacts/${generation}/.jazz-artifact-manifest.json`,
      "the jazz-napi build manifest",
    );
  } else {
    // Without a flag this stages a release from the linux-x64-gnu manifest that
    // CI release assembly downloads. Local checkouts never have that file.
    const releaseManifest = "crates/jazz-napi/provenance/jazz-napi.linux-x64-gnu.manifest.json";
    if (!existsSync(join(root, releaseManifest)))
      throw new Error(
        `release mode (no flag) reads the NAPI manifest that CI release assembly downloads ` +
          `(${releaseManifest}); it is not present in a local checkout. ${localBuildHint}`,
      );
    napi = read(join(root, releaseManifest));
  }
  for (const [name, manifest] of [
    ["wasm", wasm],
    ["napi", napi],
  ])
    if (!/^[a-f0-9]{64}$/.test(manifest.nativeArtifactFingerprint ?? ""))
      throw new Error(`${name} manifest lacks a native fingerprint`);
  if (
    wasm.kind !== "wasm" ||
    wasm.profile !== (profiling ? "profiling" : local ? "fast" : "release")
  )
    throw new Error("downloaded WASM manifest has the wrong kind/profile");
  const artifacts = wasm.artifacts;
  if (!Array.isArray(artifacts) || artifacts.length !== wasmArtifactFiles.length)
    throw new Error("downloaded WASM manifest must list each generated artifact exactly once");
  const artifactNames = artifacts.map((artifact) => artifact?.file);
  if (
    new Set(artifactNames).size !== wasmArtifactFiles.length ||
    wasmArtifactFiles.some((file) => !artifactNames.includes(file))
  )
    throw new Error("downloaded WASM manifest must list each generated artifact exactly once");
  for (const artifact of artifacts) {
    if (!artifact || typeof artifact.file !== "string")
      throw new Error("downloaded WASM manifest has an invalid artifact entry");
    const path = join(root, "crates/jazz-wasm/pkg", artifact.file);
    const hash =
      existsSync(path) &&
      lstatSync(path).isFile() &&
      lstatSync(path).size > 0 &&
      /^[a-f0-9]{64}$/.test(artifact.sha256 ?? "") &&
      createHash("sha256").update(readFileSync(path)).digest("hex");
    if (hash !== artifact.sha256)
      throw new Error(`downloaded WASM artifact hash mismatch: ${artifact.file}`);
  }
  if (napi.kind !== "napi" || napi.profile !== "release")
    throw new Error("downloaded NAPI manifest has the wrong kind/profile");
  const runtime = join(root, "packages/jazz-tools/src/runtime");
  const fingerprintSource = (name, fingerprint) =>
    `// Generated by release assembly.\nexport const ${name} =\n  ${JSON.stringify(fingerprint)} as const;\n`;
  writeFileSync(
    join(runtime, "native-artifact-fingerprint-napi.ts"),
    fingerprintSource("EXPECTED_NAPI_ARTIFACT_FINGERPRINT", napi.nativeArtifactFingerprint),
  );
  writeFileSync(
    join(runtime, "native-artifact-fingerprint-wasm.ts"),
    fingerprintSource("EXPECTED_WASM_ARTIFACT_FINGERPRINT", wasm.nativeArtifactFingerprint),
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = resolve(fileURLToPath(new URL("../..", import.meta.url)));
  try {
    stageNativeFingerprints(root, {
      local: process.argv.includes("--local"),
      workspace: process.argv.includes("--workspace"),
      profiling: process.argv.includes("--profiling"),
    });
  } catch (error) {
    console.error(`stage native fingerprints: ${error.message}`);
    process.exitCode = 1;
  }
}
