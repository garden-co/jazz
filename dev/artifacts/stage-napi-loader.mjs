#!/usr/bin/env node
import { copyFileSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export function stageNapiLoader(root, platform) {
  if (!platform) throw new Error("usage: stage-napi-loader.mjs <platform>");
  const packageDir = join(root, "crates/jazz-napi");
  const pointer = readFileSync(join(packageDir, "native-binding.pointer.cjs"), "utf8");
  const generation = /\.native-artifacts\/(generation-[A-Za-z0-9.-]+)\/index\.js/.exec(
    pointer,
  )?.[1];
  const fingerprint = /expectedNativeArtifactFingerprint:\s*"([a-f0-9]{64})"/.exec(pointer)?.[1];
  if (!generation || !fingerprint) throw new Error("active NAPI generation pointer is invalid");
  const stage = join(packageDir, ".native-artifacts", generation);
  const binding = join(stage, `jazz-napi.${platform}.node`);
  for (const path of [
    binding,
    join(stage, "index.js"),
    join(stage, ".jazz-artifact-manifest.json"),
  ])
    if (!existsSync(path)) throw new Error(`active NAPI generation is missing ${path}`);
  const manifest = JSON.parse(readFileSync(join(stage, ".jazz-artifact-manifest.json"), "utf8"));
  if (manifest.kind !== "napi" || manifest.profile !== "release")
    throw new Error("active NAPI generation manifest has the wrong kind/profile");
  if (manifest.nativeArtifactFingerprint !== fingerprint)
    throw new Error("active NAPI pointer fingerprint does not match its sealed manifest");
  copyFileSync(binding, join(packageDir, `jazz-napi.${platform}.node`));
  copyFileSync(join(stage, "index.js"), join(packageDir, "native-loader.cjs"));
  copyFileSync(
    join(stage, ".jazz-artifact-manifest.json"),
    join(packageDir, `jazz-napi.${platform}.manifest.json`),
  );
  writeFileSync(
    join(packageDir, "native-artifact-fingerprint.cjs"),
    `// Generated by dev/artifacts/stage-napi-loader.mjs.\nmodule.exports = { expectedNativeArtifactFingerprint: ${JSON.stringify(fingerprint)} };\n`,
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = resolve(fileURLToPath(new URL("../..", import.meta.url)));
  try {
    stageNapiLoader(root, process.argv[2]);
  } catch (error) {
    console.error(`stage NAPI loader: ${error.message}`);
    process.exitCode = 1;
  }
}
