#!/usr/bin/env bash
# Puts libjazz_ffi's shared library for each platform into jazz-go, so the
# Go module needs no cgo and no download: run at release, on the commit
# tagged packages/jazz-go/v<version> (not on main, which carries no
# binaries).
#
#   dev/scripts/go-embed-ffi-libraries.sh <dir with libjazz_ffi-<os>-<arch>.tar.gz>
#
# Each archive's libjazz_ffi.so / .dylib becomes
# packages/jazz-go/lib/<goos>_<goarch>/, with an embed_<goos>_<goarch>.go
# that embeds it for that platform only.
set -euo pipefail
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
artifacts="${1:?usage: $0 <dir with libjazz_ffi-<os>-<arch>.tar.gz>}"
pkg="${root}/packages/jazz-go"
for archive in "${artifacts}"/libjazz_ffi-*.tar.gz; do
  target="$(basename "${archive}" .tar.gz)"
  target="${target#libjazz_ffi-}"
  os="${target%-*}"
  arch="${target#*-}"
  case "${os}" in linux) goos=linux lib=libjazz_ffi.so ;; darwin) goos=darwin lib=libjazz_ffi.dylib ;; *) echo "skip ${target}"; continue ;; esac
  case "${arch}" in x86_64) goarch=amd64 ;; aarch64) goarch=arm64 ;; *) echo "skip ${target}"; continue ;; esac
  dir="${pkg}/lib/${goos}_${goarch}"
  mkdir -p "${dir}"
  # The release archives list their files as ./<name> (tar -C <dir> .):
  # extract it all and take the library, whichever way it is listed.
  unpacked="$(mktemp -d)"
  tar -xzf "${archive}" -C "${unpacked}"
  [ -f "${unpacked}/${lib}" ] || { echo "${archive} has no ${lib} at its root" >&2; exit 1; }
  cp "${unpacked}/${lib}" "${dir}/${lib}"
  rm -rf "${unpacked}"
  name="embedded$(tr '[:lower:]' '[:upper:]' <<< "${goos:0:1}")${goos:1}$(tr '[:lower:]' '[:upper:]' <<< "${goarch:0:1}")${goarch:1}"
  cat > "${pkg}/embed_${goos}_${goarch}.go" <<GO
// Code generated by dev/scripts/go-embed-ffi-libraries.sh. DO NOT EDIT.

//go:build ${goos} && ${goarch}

package jazz

import _ "embed"

//go:embed lib/${goos}_${goarch}/${lib}
var ${name} []byte

func init() { embeddedLibrary = ${name} }
GO
  echo "embedded ${goos}/${goarch}: $(du -h "${dir}/${lib}" | cut -f1)"
done
