#!/usr/bin/env bash
# Give suites their toolchain and admitted artifacts without forwarding CI credentials.
allowed=(
  PATH HOME USER SHELL TMPDIR TMP TEMP RUNNER_TEMP LANG LC_ALL LC_CTYPE TERM
  SYSTEMROOT SystemRoot WINDIR COMSPEC ComSpec PATHEXT USERPROFILE APPDATA LOCALAPPDATA
  CI RUSTC RUSTC_WRAPPER RUSTUP_HOME CARGO_HOME "${!SCCACHE_@}" PLAYWRIGHT_BROWSERS_PATH
  JAZZ_TEST_SEALED_TOOLS_DIST JAZZ_TEST_SEALED_INSPECTOR_DIST JAZZ_RN_TEST_BRIDGE
  JAZZ_CORRECTNESS_ARTIFACT_RUN JAZZ_CORRECTNESS_WASM_PACKAGE
  JAZZ_CORRECTNESS_NAPI_BINDING JAZZ_CORRECTNESS_NAPI_FINGERPRINT
  JAZZ_CORRECTNESS_CONSUMER_CAPABILITY JAZZ_CORRECTNESS_CONSUMER_TOKEN
)
suite_env=()
for name in "${allowed[@]}"; do
  if [[ -n ${!name+x} ]]; then
    suite_env+=("$name=${!name}")
  fi
done
exec env -i "${suite_env[@]}" "$@"
