// The Rust public schema builder and postcard producer own these fixture bytes.
// Run from the repository root after changing examples/support/device_fixture.rs.
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
const root = path.resolve(import.meta.dirname, "..");
const fixture = JSON.parse(
  execFileSync(
    "cargo",
    [
      "run",
      "-p",
      "jazz-native-relay",
      "--example",
      "rn_edge_session_harness",
      "--",
      "--print-fixture",
    ],
    { cwd: path.resolve(root, "../.."), encoding: "utf8" },
  ),
);
fs.writeFileSync(
  path.join(root, "native/device-fixture.json"),
  JSON.stringify(fixture, null, 2) + "\n",
);
fs.writeFileSync(
  path.join(root, "src/scope-fixture.ts"),
  `// Generated by scripts/generate-scope-fixture.mjs; do not hand-edit.\nexport const scopeQuery = Uint8Array.from(${JSON.stringify(fixture.scopeQuery)});\nexport const scopeCells = ${JSON.stringify(fixture.scopeCells)} as const;\n`,
);
for (const file of ["native/ios/JazzDeviceFixture.mm", "ios/JazzDeviceFixture.mm"]) {
  const target = path.join(root, file);
  fs.writeFileSync(
    target,
    fs
      .readFileSync(target, "utf8")
      .replace(
        /  NSString \*schema = .*;/,
        `  NSString *schema = @${JSON.stringify(JSON.stringify(fixture.schema))};`,
      ),
  );
}
const target = path.join(root, "android/app/build.gradle");
fs.writeFileSync(
  target,
  fs
    .readFileSync(target, "utf8")
    .replace(
      /^.*buildConfigField "String", "JAZZ_DEVICE_SCHEMA_JSON".*$/m,
      `        buildConfigField "String", "JAZZ_DEVICE_SCHEMA_JSON", ${JSON.stringify(JSON.stringify(JSON.stringify(fixture.schema)))}`,
    ),
);

execFileSync(
  "pnpm",
  [
    "exec",
    "oxfmt",
    path.join(root, "src/scope-fixture.ts"),
    path.join(root, "native/device-fixture.json"),
  ],
  { cwd: path.resolve(root, "../.."), stdio: "inherit" },
);
