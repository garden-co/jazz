// The Rust public schema builder and postcard producer own these fixture bytes.
// Run from the repository root after changing examples/support/device_fixture.rs.
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
const root = path.resolve(import.meta.dirname, "..");
const fixture = JSON.parse(
  execFileSync(
    "cargo",
    [
      "run",
      "-p",
      "jazz-native-relay",
      "--example",
      "rn_edge_session_harness",
      "--",
      "--print-fixture",
    ],
    { cwd: path.resolve(root, "../.."), encoding: "utf8" },
  ),
);
fs.writeFileSync(
  path.join(root, "native/device-fixture.json"),
  JSON.stringify(fixture, null, 2) + "\n",
);
fs.writeFileSync(
  path.join(root, "src/scope-fixture.ts"),
  `// Generated by scripts/generate-scope-fixture.mjs; do not hand-edit.\nexport const schemaSource = ${JSON.stringify(JSON.stringify(fixture.schema))};\nexport const scopeQuery = Uint8Array.from(${JSON.stringify(fixture.scopeQuery)});\nexport const todosQuery = Uint8Array.from(${JSON.stringify(fixture.todosQuery)});\nexport const scopeCells = ${JSON.stringify(fixture.scopeCells)} as const;\n`,
);
execFileSync(
  "pnpm",
  [
    "exec",
    "oxfmt",
    path.join(root, "src/scope-fixture.ts"),
    path.join(root, "native/device-fixture.json"),
  ],
  { cwd: path.resolve(root, "../.."), stdio: "inherit" },
);
