// ---- jazz-ffi for the JVM: the host's library and bindings ----

val withFfi = (findProperty("jazzFfi") as String?) != "skip"
val cargoProfile = (findProperty("cargoProfile") as String?) ?: "debug"
val ffiLib = repo.resolve(
    "target/$cargoProfile/" + when {
        System.getProperty("os.name").lowercase().startsWith("mac") -> "libjazz_ffi.dylib"
        System.getProperty("os.name").lowercase().startsWith("windows") -> "jazz_ffi.dll"
        else -> "libjazz_ffi.so"
    },
)
val uniffiOut = layout.buildDirectory.dir("generated/uniffi/jvm")
val uniffiBindings = (findProperty("uniffiBindings") as String?)?.let { file(it) }
if (uniffiBindings != null) {
    check(findProperty("nativeLibs") != null) { "-PuniffiBindings needs -PnativeLibs" }
    check(uniffiBindings.resolve("uniffi/jazz_ffi/jazz_ffi.kt").isFile) { "-PuniffiBindings=$uniffiBindings lacks uniffi/jazz_ffi/jazz_ffi.kt" }
}

val cargoBuildFfi by tasks.registering(Exec::class) {
    description = "Builds crates/jazz-ffi."
    enabled = uniffiBindings == null
    workingDir = repo
    commandLine(listOf("cargo", "build", "-p", "jazz-ffi") + if (cargoProfile == "release") listOf("--release") else emptyList())
}

val generateUniffi by tasks.registering(Exec::class) {
    description = "Generates jazz-ffi's Kotlin bindings with uniffi-bindgen (the JVM target's)."
    dependsOn(cargoBuildFfi)
    workingDir = repo
    enabled = uniffiBindings == null
    inputs.file(ffiLib)
    outputs.dir(uniffiOut)
    commandLine(
        "cargo", "run", "-q", "-p", "jazz-ffi", "--features", "bindgen", "--bin", "uniffi-bindgen", "--",
        "generate", "--library", ffiLib.path, "--language", "kotlin", "--no-format",
        "--out-dir", uniffiOut.get().asFile.path,
    )
}

// ---- jazz-ffi for Android: cargo-ndk's libraries and their bindings ----

val androidCargoProfile = (findProperty("androidCargoProfile") as String?) ?: "release-mobile"
val abis = ((findProperty("androidAbis") as String?) ?: "arm64-v8a,armeabi-v7a,x86_64").split(",").map { it.trim() }
val jniLibsOut = layout.buildDirectory.dir("jniLibs")
val androidUniffiOut = layout.buildDirectory.dir("generated/uniffi/android")
val prebuiltJniLibs = (findProperty("prebuiltJniLibs") as String?)?.let { file(it) }
val androidUniffiBindings = (findProperty("androidUniffiBindings") as String?)?.let { file(it) }
if (androidUniffiBindings != null) {
    check(androidUniffiBindings.resolve("uniffi/jazz_ffi/jazz_ffi.kt").isFile) {
        "-PandroidUniffiBindings=$androidUniffiBindings lacks uniffi/jazz_ffi/jazz_ffi.kt"
    }
}

val cargoNdkFfi by tasks.registering(Exec::class) {
    description = "Cross-compiles crates/jazz-ffi for the Android ABIs with cargo-ndk."
    // Skipped (and replaced by copyPrebuiltJniLibs) with -PprebuiltJniLibs.
    enabled = prebuiltJniLibs == null
    workingDir = repo
    outputs.dir(jniLibsOut)
    outputs.upToDateWhen { false } // cargo decides what to rebuild
    // cargo-ndk only adds files: drop ABIs (or profiles) a previous run left.
    doFirst { delete(jniLibsOut) }
    commandLine(
        listOf("cargo", "ndk", "--platform", minSdkVersion.toString()) +
            abis.flatMap { listOf("-t", it) } +
            listOf("-o", jniLibsOut.get().asFile.path, "build", "-p", "jazz-ffi", "--profile", androidCargoProfile),
    )
}

// -PprebuiltJniLibs: exactly <abi>/libjazz_ffi.so for each ABI, into the
// same directory cargo-ndk writes, so the AAR packs the same layout.
val copyPrebuiltJniLibs by tasks.registering(Sync::class) {
    description = "Copies the prebuilt jazz-ffi libraries (-PprebuiltJniLibs) into jniLibs."
    enabled = prebuiltJniLibs != null
    if (prebuiltJniLibs != null) {
        val missing = abis.filterNot { prebuiltJniLibs.resolve("$it/libjazz_ffi.so").isFile }
        check(missing.isEmpty()) { "-PprebuiltJniLibs=$prebuiltJniLibs lacks libjazz_ffi.so for $missing" }
        from(prebuiltJniLibs) { abis.forEach { include("$it/libjazz_ffi.so") } }
    }
    into(jniLibsOut)
}

// The bindings come from the very library the AAR ships (the first ABI's),
// so they always match its UniFFI scaffolding.
val generateUniffiAndroid by tasks.registering(Exec::class) {
    description = "Generates jazz-ffi's Kotlin bindings with uniffi-bindgen (the Android target's)."
    dependsOn(cargoNdkFfi, copyPrebuiltJniLibs)
    enabled = androidUniffiBindings == null
    workingDir = repo
    val lib = jniLibsOut.get().file("${abis.first()}/libjazz_ffi.so").asFile
    inputs.file(lib)
    outputs.dir(androidUniffiOut)
    commandLine(
        "cargo", "run", "-q", "-p", "jazz-ffi", "--features", "bindgen", "--bin", "uniffi-bindgen", "--",
        "generate", "--library", lib.path, "--language", "kotlin", "--no-format",
        "--out-dir", androidUniffiOut.get().asFile.path,
    )
}

kotlin {
    // The sources uniffi-bindgen generates declare no visibility.
    explicitApiWarning()

    jvm {
        compilerOptions { jvmTarget.set(JvmTarget.JVM_17) }
        val main = compilations.getByName("main")
        val test = compilations.getByName("test")
        // jazz-codegen's Kotlin goldens must compile against this runtime:
        // chat-react (the widest types) with the tests (jvmTest, below),
        // kotlin-edges (names that could hide packages or members) on its own,
        // as both declare package jazzapp.
        compilations.create("edges") {
            associateWith(main)
            defaultSourceSet.kotlin.srcDir(repo.resolve("crates/jazz-codegen/tests/apps/kotlin-edges"))
        }
        // Goldens with tests of their own (each declares package jazzapp, so
        // each gets a compilation): kotlin-computed (transforms, computed fields).
        val computed = compilations.create("computed") {
            associateWith(main)
            associateWith(test)
            defaultSourceSet {
                kotlin.srcDir(repo.resolve("crates/jazz-codegen/tests/apps/kotlin-computed"))
                dependencies {
                    implementation(kotlin("test-junit5"))
                    implementation("org.jetbrains.kotlinx:kotlinx-coroutines-test:1.10.2")
                }
            }
        }
        testRuns.create("computed") {
            setExecutionSourceFrom(computed)
            executionTask.configure { useJUnitPlatform() }
        }
    }
    if (withAndroid) {
        androidTarget {
            compilerOptions { jvmTarget.set(JvmTarget.JVM_17) }
            publishLibraryVariants("release")
        }
    }

    sourceSets {
        all {
            languageSettings.optIn("kotlin.concurrent.atomics.ExperimentalAtomicApi")
        }
        commonMain.dependencies {
            api("org.jetbrains.kotlinx:kotlinx-serialization-json:1.9.0")
            api("org.jetbrains.kotlinx:kotlinx-coroutines-core:1.10.2")
        }
        jvmMain {
            // The platform seam, and the UniFFI adapter with its bindings: the
            // same sources as Android's (KT-42466: no shared JVM+Android source set).
            kotlin.srcDir("src/jna/kotlin")
            if (withFfi) {
                kotlin.srcDir("src/ffi/kotlin")
                // builtBy: every reader (compile, the sources jars) runs generateUniffi first.
                kotlin.srcDir(uniffiBindings ?: files(uniffiOut).builtBy(generateUniffi))
            }
            dependencies { implementation("net.java.dev.jna:jna:5.17.0") }
        }
        jvmTest {
            kotlin.srcDir(repo.resolve("crates/jazz-codegen/tests/apps/chat-react"))
            dependencies {
                implementation(kotlin("test"))
                implementation("org.jetbrains.kotlinx:kotlinx-coroutines-test:1.10.2")
            }
        }
        if (withAndroid) {
            androidMain {
                kotlin.srcDir("src/jna/kotlin")
                kotlin.srcDir("src/ffi/kotlin")
                // builtBy: AGP's androidReleaseSourcesJar isn't a Gradle Jar the hook
                // below reaches; the source dir itself carries the task.
                kotlin.srcDir(androidUniffiBindings ?: files(androidUniffiOut).builtBy(generateUniffiAndroid))
                // JNA's Android build: the same classes plus libjnidispatch.so per ABI.
                dependencies { implementation("net.java.dev.jna:jna:5.17.0@aar") }
            }
        }
    }
}

