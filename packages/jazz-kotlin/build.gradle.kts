// jazz-kotlin: the Kotlin runtime for Jazz apps, over jazz-ffi, as one Kotlin
// Multiplatform library with two targets:
//   jvm      the JVM (desktop, server): the UniFFI bindings over JNA, with
//            libjazz_ffi bundled as JNA resources;
//   android  an Android library (AAR): the same UniFFI sources, with
//            crates/jazz-ffi cross-compiled by cargo-ndk into jniLibs for
//            arm64-v8a, armeabi-v7a and x86_64, and JNA's Android AAR.
// commonMain is the API; src/jna/kotlin (its platform seam) and src/ffi/kotlin
// (the UniFFI adapter) are compiled into both targets, as are the generated
// bindings. Published (maven-publish) as tools.jazz:jazz-kotlin, with Gradle
// module metadata that picks tools.jazz:jazz-kotlin-jvm or
// tools.jazz:jazz-kotlin-android.
//
// Gradle 8.14 (no wrapper is committed; dev/scripts/kotlin-toolchain.sh pins one).
//
// The JVM target:
//   `gradle jvmTest` first builds crates/jazz-ffi with cargo and generates its
//   Kotlin bindings with uniffi-bindgen; -PjazzFfi=skip builds without them
//   (tests then use a fake native). -PuniffiBindings=<dir> (with -PnativeLibs)
//   takes bindings already generated by this same uniffi-bindgen command
//   instead: no cargo at all. -PnativeLibs=<dir> bundles every platform's
//   libjazz_ffi, in JNA's layout (dev/scripts/build-kotlin-dist.sh).
//   -PcargoProfile picks the host build's Cargo profile (default debug).
//
// The Android target, there when an Android SDK is (ANDROID_HOME,
// ANDROID_SDK_ROOT or local.properties' sdk.dir; -PjazzAndroid=skip leaves it
// out). It needs platforms;android-36, build-tools;36.0.0, ndk;27.1.12297006
// and cargo-ndk on PATH: dev/scripts/test-kotlin-android.sh sets all up.
// `gradle assembleRelease` writes build/outputs/aar/jazz-kotlin-release.aar.
//   -PandroidCargoProfile (default release-mobile, the size-oriented one jazz-rn
//   ships); -PandroidAbis=arm64-v8a,… narrows the ABIs. -PprebuiltJniLibs=<dir>
//   packages <dir>/<abi>/libjazz_ffi.so built elsewhere by this same cargo-ndk
//   command instead of running cargo-ndk; -PandroidUniffiBindings=<dir> takes
//   the bindings generateUniffiAndroid made from such a build's first ABI.
//
// The whole Maven repository (every publication, signed) into <dir>:
//   gradle publishAllPublicationsToJazzLocalRepository -PjazzLocalRepo=<dir> \
//     -PnativeLibs=<natives> [-PuniffiBindings=…] [-PprebuiltJniLibs=… -PandroidUniffiBindings=…]

