// Copy the inspector overlay's embedded build into jazz-tools' own dist so the
// published package is self-contained (no jazz-inspector dependency), and
// write the same files into dist/backend/inspector-ui-files.js, the module
// createJazz serves the Inspector from (see src/backend/inspect-ui.ts). A
// module ships wherever the code does; files read from disk at runtime are
// left out by bundlers and output file tracing (Next.js on Vercel).
// Run from the workspace (`pnpm --filter jazz-tools run stage:inspector-overlay`)
// after the inspector's embedded build to reproduce the published layout locally.
import {
  cp,
  lstat,
  mkdir,
  mkdtemp,
  readFile,
  readdir,
  rename,
  rm,
  writeFile,
} from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

async function pathExists(path) {
  try {
    await lstat(path);
    return true;
  } catch (error) {
    if (error.code === "ENOENT") return false;
    throw error;
  }
}

async function validateOverlay(directory) {
  const embeddedPath = join(directory, "embedded.html");
  const embeddedStat = await lstat(embeddedPath);
  if (!embeddedStat.isFile()) {
    throw new Error("Inspector overlay embedded.html must be a regular file");
  }

  async function rejectUnsafeEntries(path) {
    for (const entry of await readdir(path, { withFileTypes: true })) {
      const entryPath = join(path, entry.name);
      if (entry.isSymbolicLink()) {
        throw new Error(`Inspector overlay must not contain symlinks: ${entry.name}`);
      }
      if (entry.isDirectory()) {
        await rejectUnsafeEntries(entryPath);
      } else if (!entry.isFile()) {
        throw new Error(`Inspector overlay contains an unsupported entry: ${entry.name}`);
      }
    }
  }

  await rejectUnsafeEntries(directory);
}

/** Every file below `directory`, by its `/`-separated path. */
async function filesBelow(directory, prefix = "") {
  const files = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) files.push(...(await filesBelow(join(directory, entry.name), path)));
    else files.push(path);
  }
  return files.sort();
}

// One module per file, imported only when that file is asked for: the build
// carries the WASM runtime and workers (megabytes) next to a page of a few
// kilobytes, and a request for the page shouldn't load them all.
async function writeUiModule(directory) {
  const entries = [];
  const partialDir = `${uiFilesDir}.partial`;
  await rm(partialDir, { recursive: true, force: true });
  await mkdir(partialDir, { recursive: true });
  let index = 0;
  for (const path of await filesBelow(directory)) {
    const encoded = (await readFile(join(directory, ...path.split("/")))).toString("base64");
    const name = `${index++}.js`;
    await writeFile(
      join(partialDir, name),
      `// ${path}, as base64. Generated by scripts/stage-inspector-overlay.mjs.\nexport default ${JSON.stringify(encoded)};\n`,
    );
    entries.push(`  ${JSON.stringify(path)}: () => import("./inspector-ui/${name}"),`);
  }
  const source =
    "// Generated by scripts/stage-inspector-overlay.mjs: the Inspector UI's files,\n" +
    "// each a module holding it as base64. See src/backend/inspector-ui-files.ts.\n" +
    `export const INSPECTOR_UI_FILES = {\n${entries.join("\n")}\n};\n`;
  await mkdir(dirname(uiModule), { recursive: true });
  await rm(uiFilesDir, { recursive: true, force: true });
  await rename(partialDir, uiFilesDir);
  const partial = `${uiModule}.partial`;
  await writeFile(partial, source);
  await rename(partial, uiModule);
  // tsc's map is for the empty placeholder this replaces.
  await rm(`${uiModule}.map`, { force: true });
}

const here = dirname(fileURLToPath(import.meta.url)); // packages/jazz-tools/scripts
const packageRoot = dirname(here);
const src = join(here, "../../inspector/dist-embedded");
const dest = join(here, "../dist/dev/inspector-overlay/embedded");
const uiModule = join(here, "../dist/backend/inspector-ui-files.js");
const uiFilesDir = join(here, "../dist/backend/inspector-ui");
const parent = dirname(dest);
await mkdir(parent, { recursive: true });
const backup = join(parent, ".inspector-overlay-backup");
// Promotion uses two renames, so interruption can briefly leave dest absent; the next run recovers backup.
let destinationExists = await pathExists(dest);
if (!destinationExists && (await pathExists(backup))) {
  // Recover an interrupted promotion before attempting to stage a replacement.
  await rename(backup, dest);
  destinationExists = true;
} else if (destinationExists && (await pathExists(backup))) {
  // A completed promotion may have been interrupted before deleting its old backup.
  await rm(backup, { recursive: true, force: true });
}
// Keep interrupted stage trees outside dist so packaging cannot include partial assets.
const stage = await mkdtemp(join(packageRoot, ".inspector-overlay-stage-"));
let primaryError;

try {
  await cp(src, stage, { recursive: true });
  await validateOverlay(stage);

  if (destinationExists) await rename(dest, backup);

  try {
    await rename(stage, dest);
  } catch (promotionError) {
    if (destinationExists) {
      try {
        await rename(backup, dest);
      } catch (rollbackError) {
        throw new Error(
          `Could not promote inspector overlay and rollback failed; backup retained at ${backup}`,
          { cause: new AggregateError([promotionError, rollbackError]) },
        );
      }
    }
    throw promotionError;
  }

  if (destinationExists) await rm(backup, { recursive: true, force: true });
  await writeUiModule(dest);
  console.log(`Staged inspector overlay assets → ${dest} and ${uiModule}`);
} catch (error) {
  primaryError = error;
  throw error;
} finally {
  try {
    await rm(stage, { recursive: true, force: true });
  } catch (cleanupError) {
    if (!primaryError) throw cleanupError;
  }
}
